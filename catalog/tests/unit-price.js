// Цена за килограмм и за литр: «69 ₽ · 986 ₽/кг».
/* Веса товара в 1С нет ни в одном справочнике — он написан в названии, и мы
 * его оттуда достаём. Названия в базе живые, с описками, поэтому правила
 * выведены из 10 673 настоящих названий владельца. Главное правило разборщика:
 * сомневаешься — молчи. Здесь проверяем и то, что он считает, и то, о чём он
 * ПРАВИЛЬНО молчит: молчание тут такая же часть работы, как и ответ. */
const { chromium, newPage, runner } = require('./helpers');

(async () => {
  const b = await chromium.launch();
  const { chk, done } = runner('ЦЕНА ЗА КГ И ЛИТР');
  const { page, errs } = await newPage(b, { products: [], groups: [] });

  const calc = (cases) => page.evaluate((list) => list.map(([name, price, weighted]) => {
    const P = window.WM_PUBLISH;
    return P._unitPrice({ name, retail_price: price, is_weighted: !!weighted });
  }), cases);

  // ── 1. Обычные случаи ──
  const ok = await calc([
    ['Ulker Альбени XXL 70г', 69],
    ['Лола Финики Мазафати 550г', 260],
    ['Вкусно Сок Апельсин 0,2л', 20],
    ['Крокант Конфеты 500г', 510],
    ['Печенье Овсяное 5кг', 1200],
  ]);
  chk(ok[0] === '986 ₽/кг', `70 грамм за 69 ₽ → ${ok[0]}`);
  chk(ok[1] === '473 ₽/кг', `550 грамм за 260 ₽ → ${ok[1]}`);
  chk(ok[2] === '100 ₽/л', `0,2 литра за 20 ₽ → ${ok[2]}`);
  chk(ok[3] === '1 020 ₽/кг', `тысячи с пробелом: ${ok[3]}`);
  chk(ok[4] === '240 ₽/кг', `5 кг за 1200 ₽ → ${ok[4]}`);

  /* ── 2. Описки в 1С ──
     «Агуша Вода 0,33мл» — не треть миллилитра, а 0,33 литра: столько никто не
     продаёт. Такие названия в базе есть, и без этого правила покупатель видел
     бы «136 364 ₽/л». */
  const typo = await calc([
    ['Агуша Вода 0,33мл', 45],
    ['7UP Напиток ж/б 0,30мл', 60],
    ['Восход Хлеб Столовый Нарезной 0,6г', 45],
    ['БМК Молоко 6% 0,975 мл', 195],
  ]);
  chk(typo[0] === '136 ₽/л', `«0,33мл» понято как 0,33 литра (${typo[0]})`);
  chk(typo[1] === '200 ₽/л', `«0,30мл» понято как 0,30 литра (${typo[1]})`);
  chk(typo[2] === '75 ₽/кг', `«0,6г» хлеба понято как 0,6 кг (${typo[2]})`);
  chk(typo[3] === '200 ₽/л', `«0,975 мл» молока понято как 0,975 л (${typo[3]})`);

  // ── 3. Упаковка из нескольких штук ──
  const packs = await calc([['Вода Питьевая 6х1,5л', 350], ['Сок 2х0,2л', 40]]);
  chk(packs[0] === '39 ₽/л', `«6х1,5л» — это 9 литров, а не 1,5 (${packs[0]})`);
  chk(packs[1] === '100 ₽/л', `«2х0,2л» посчитано как 0,4 литра (${packs[1]})`);

  // ── 4. Когда правильно промолчать ──
  const quiet = await calc([
    ['тетрадь 96л', 250],                       // 96 листов, а не литров
    ['Пакеты для Мусора 240л', 250],            // литры есть, но цена за литр бессмысленна
    ['Choco Break Печенье 2кг', 15],            // цена явно не за коробку
    ['J7 Напиток Апельсин 300л', 135],          // описка: 300 мл
    ['Сыр Российский', 790, true],              // весовой: цена и так за кг
    ['Хлеб', 45],                               // веса в названии нет
    ['Молоко 1л', 0],                           // цены нет
  ]);
  const names = ['тетрадь 96 листов', 'мусорные пакеты 240 л', 'печенье 2 кг за 15 ₽',
    'описка «300л»', 'весовой товар', 'без веса в названии', 'без цены'];
  quiet.forEach((v, i) => chk(!v, `молчим: ${names[i]}${v ? ' — а показали «' + v + '»' : ''}`));

  // ── 5. Видно там, где человек смотрит на цену ──
  await page.evaluate(() => {
    const P = window.WM_PUBLISH, s = P._state();
    s.products = [{ id: 'u1', name: 'Ulker Альбени XXL 70г', code: '1', retail_price: 69,
      unit: 'шт', photos: [], barcodes: ['4600000000011'], group_id: 'g1', stock_state: 'in' }];
    P.buildIndex(); P.renderAll();
  });
  await page.waitForTimeout(300);
  const grid = await page.evaluate(() => document.getElementById('productGrid').innerText.replace(/\s+/g, ' '));
  chk(/986 ₽\/кг/.test(grid), `в списке товаров видно цену за кг (${grid.slice(0, 50)})`);
  const tag = await page.evaluate(async () => {
    window.WM_PUBLISH._scanPrice('4600000000011');
    await new Promise((r) => setTimeout(r, 250));
    return document.getElementById('scanResult').innerText.replace(/\s+/g, ' ');
  });
  chk(/986 ₽\/кг/.test(tag), `на ценнике покупателя тоже (${tag.slice(0, 50)})`);

  chk(!errs.length, `нет сбоев JS (${errs.length}${errs.length ? ': ' + errs[0] : ''})`);
  await done(b);
})();
