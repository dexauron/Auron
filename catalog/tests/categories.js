const products = ОЖИДАЕМ.map(([n], i) => ({
  id: 'p' + i, name: n, code: String(1000 + i), group_id: 'g1',
  retail_price: 50 + i, is_weighted: false, unit: 'шт', photos: [], created_at: '2026-01-01',
}));
// товар, который по названию не узнать — честно уходит в «Прочее»
products.push({ id: 'px', name: 'Носки мужские хлопок', code: '1999', group_id: 'g1',
  retail_price: 120, is_weighted: false, unit: 'шт', photos: [], created_at: '2026-01-01' });
// товар с ручной категорией — она должна перебивать всё
products.push({ id: 'pm', name: 'Носки мужские хлопок', code: '1998', group_id: 'g1', category: 'Дом и химия',
  retail_price: 120, is_weighted: false, unit: 'шт', photos: [], created_at: '2026-01-01' });

(async () => {
  const b = await chromium.launch();
  const { chk, done } = runner('РАСКЛАДКА ПО КАТЕГОРИЯМ');
  const { page, errs } = await newPage(b, { products, groups: [{ id: 'g1', name: 'Товары' }] });
  await page.waitForTimeout(600);

  const got = await page.evaluate(() => {
    const P = window.WM_PUBLISH;
    if (!P._cat) return null;
    return Object.fromEntries(P._state().products.map((p) => [p.id, P._cat(p)]));
  });
  if (!got) { chk(false, 'приложение не отдаёт категорию товара — проверять нечего'); await done(b); return; }

  const wrong = ОЖИДАЕМ.map(([n, c], i) => [n, c, got['p' + i]]).filter(([, c, g]) => c !== g);
  console.log('--- разложено ---');
  ОЖИДАЕМ.forEach(([n], i) => console.log(`  ${(got['p' + i] || '—').padEnd(18)} ${n}`));
  console.log('---');
  chk(!wrong.length, `все ${ОЖИДАЕМ.length} товаров разложены верно по одному названию${
    wrong.length ? ': ' + wrong.map(([n, c, g]) => `«${n}» ждали ${c}, получили ${g}`).join('; ') : ''}`);

  chk(got.px === 'Прочее', `непонятный товар честно уходит в «Прочее» (${got.px})`);
  chk(got.pm === 'Дом и химия', `ручная категория перебивает название (${got.pm})`);

  // группа-мусор не должна перебивать название
  const byGroup = await page.evaluate(() => {
    const P = window.WM_PUBLISH; const s = P._state();
    s.groups = [{ id: 'g1', name: 'Бытовая химия' }];   // группа ЛЖЁТ: там молоко и хлеб
    s.products.forEach((p) => delete p._cat);
    // товары отсортированы по алфавиту — ищем по коду, а не по номеру в списке
    const by = (id) => s.products.find((x) => x.id === id);
    return { milk: P._cat(by('p0')), bread: P._cat(by('p4')), unknown: P._cat(by('px')) };
  });
  chk(byGroup.milk === 'Молочное' && byGroup.bread === 'Хлеб и выпечка',
    `неверная группа не сбивает раскладку (молоко → ${byGroup.milk}, хлеб → ${byGroup.bread})`);
  chk(byGroup.unknown === 'Дом и химия',
    `а если название ничего не говорит — группа всё же используется (${byGroup.unknown})`);

  chk(!errs.length, `нет сбоев JS (${errs.length}${errs.length ? ': ' + errs[0] : ''})`);
  await done(b);
})();
