// Повторные загрузки из 1С: каталог должен ОБНОВЛЯТЬСЯ, а не только копить.
// Данные выдуманные: настоящие выгрузки магазина в репозиторий не кладём.
const { chromium, newPage, runner } = require('./helpers');

(async () => {
  const b = await chromium.launch();
  const { chk, done } = runner('ПОВТОРНЫЕ ЗАГРУЗКИ ИЗ 1С');
  const { page, errs } = await newPage(b, {});
  await page.evaluate(() => { const P = window.WM_PUBLISH; P.ghSetToken('t'); P.applyServerless('pw'); });

  // seed — товары, уже лежащие в каталоге; files — загрузки по очереди
  const run = (seed, files) => page.evaluate(([sd, fl]) => {
    const P = window.WM_PUBLISH; const s = P._state();
    s.products = JSON.parse(JSON.stringify(sd)); s.groups = []; s.suppliers = []; s.prices = []; s.sales = []; s.unitCoef = {};
    try { for (const f of fl) P.svImportRows(f); } catch (e) { return { err: String(e.message || e) }; }
    const gName = (id) => (s.groups.find((g) => g.id === id) || {}).name || null;
    return { products: s.products.map((p) => ({ ...p, group: gName(p.group_id) })) };
  }, [seed, files]);
  const by = (r, code) => (r.products || []).find((p) => p.code === code) || {};

  const PRICE_HEAD = [['Прайс-лист на 20 октября 2026 г.'], [],
    ['Номенклатура', 'Основной штрих-код', 'Код', 'Закупочный тип цен', 'Розничный тип цен'], ['', '', '', 'RUB', 'RUB']];

  { /* Товар, которому в 1С не поставили розничную цену, принимался за
       заголовок группы, и все товары за ним до следующей группы уезжали в
       категорию с ЕГО названием. */
    const r = await run([], [[...PRICE_HEAD,
      ['Лапша', '', 1, '', ''],
      ['Лапша Тест 90г', '4600000000011', 11, 40, 60],
      ['Стакан Тест 120г', '4600000000028', 12, 217.3, ''],
      ['Лапша Другая 75г', '4600000000035', 13, 30, 45],
    ]]);
    chk(!r.err, 'прайс разобран' + (r.err ? ': ' + r.err : ''));
    chk(by(r, '13').group === 'Лапша', `товар после «товара без цены» остался в своей группе (${by(r, '13').group})`);
    chk(!(r.products || []).some((p) => p.code === '12'), 'товар без розничной цены не создан');
  }
  { // «Арт.» — отдельное слово, а не буквы внутри «Карты»/«фартуке»
    const r = await run([], [[...PRICE_HEAD,
      ['Игры', '', 2, '', ''],
      ['Карты Тест 36шт', '4600000000042', 21, 50, 80],
      ['Мишка в фартуке Арт.t426-25', '4600000000059', 22, 200, 300],
    ]]);
    chk(!by(r, '21').article, `у «Карты» нет выдуманного артикула (${by(r, '21').article})`);
    chk(by(r, '22').article === 't426-25', `артикул после «Арт.» прочитан (${by(r, '22').article})`);
  }

  const STOCK = (lines) => [['Остатки номенклатуры'], [],
    ['Номенклатура', 'код товара', 'Штрихкод', 'Группа товара', 'Базовая единица', 'Количество', 'Розничная цена'], ...lines];
  const many = (n, from) => Array.from({ length: n }, (_, i) => [`Товар ${from + i}`, String(from + i), '', 'Разное', 'шт', 5, 10]);

  { /* Товар пропал из отчёта «Остатки» — на складе его больше нет. Раньше у
       него оставался прежний остаток, и витрина писала «есть в наличии». */
    const r = await run([], [
      STOCK([['Молоко Тест', '101', '', 'Молочное', 'шт', 5, 89], ...many(10, 200)]),
      STOCK(many(10, 200)),
    ]);
    chk(by(r, '101').stock === 0, `остаток пропавшего из отчёта товара обнулён (${by(r, '101').stock})`);
    chk(by(r, '200').stock === 5, 'остаток товара из отчёта не тронут');
  }
  { // отчёт с отбором по одной группе не должен обнулять весь магазин
    const r = await run([], [
      STOCK([['Молоко Тест', '101', '', 'Молочное', 'шт', 5, 89], ...many(10, 200)]),
      STOCK([['Молоко Тест', '101', '', 'Молочное', 'шт', 4, 89]]),
    ]);
    chk(by(r, '200').stock === 5, `неполный отчёт не обнулил остальные товары (${by(r, '200').stock})`);
  }
  { // единица сменилась в 1С: шт → кг
    const r = await run([], [
      STOCK([['Конфеты Тест', '301', '', 'Конфеты', 'шт', 5, 100]]),
      STOCK([['Конфеты Тест', '301', '', 'Конфеты', 'кг', 2.5, 510]]),
    ]);
    chk(by(r, '301').unit === 'кг' && by(r, '301').is_weighted === true, `единица обновилась (${by(r, '301').unit}, вес: ${by(r, '301').is_weighted})`);
  }
  { /* Штрихкод перенесли в 1С на новую карточку. Старая держала его вечно, и
       один код висел на двух товарах. */
    const seed = [
      { id: 'old', name: 'Крахмал Тест 200г', code: '876', barcodes: ['4600000000066'], photos: [] },
      { id: 'new', name: 'Крахмал Тест 200гр', code: '23330', barcodes: [], photos: [] },
    ];
    const r = await run(seed, [[['Имя объекта: Штрих коды'], [],
      ['Штрих код', '', 'Единица', '', 'Номенклатура'],
      ['4600000000066', '', 'шт', '', 'Крахмал Тест 200гр']]]);
    chk((by(r, '23330').barcodes || []).includes('4600000000066'), 'штрихкод у товара, которому его отдала 1С');
    chk(!(by(r, '876').barcodes || []).includes('4600000000066'), 'у прежнего владельца штрихкод снят');

    const r2 = await run(seed, [STOCK([['Крахмал Тест 200гр', '23330', '4600000000066', 'Бакалея', 'шт', 3, 70]])]);
    chk(!(by(r2, '876').barcodes || []).includes('4600000000066'), 'основной штрихкод из остатков тоже переезжает');
  }

  chk(!errs.length, `нет сбоев JS (${errs.length})`);
  await done(b);
})();
