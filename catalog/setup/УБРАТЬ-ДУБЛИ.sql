-- Когда нужно: если после повторного импорта каталог «задвоился»
--   (старая версия приложения вставляла товары без кода заново).
-- Что делает: оставляет ОДИН товар на каждое «имя + штрихкоды»,
--   приоритет — строка с кодом кассы, затем самая ранняя.
--   Разные товары с одинаковым именем, но РАЗНЫМИ штрихкодами — не трогает.
-- Как применить: Supabase → SQL Editor → вставить → Run. Выполнять на
--   ОБНОВЛЁННОЙ версии приложения (где импорт больше не двоит).
-- Безопасно повторять: второй запуск уже ничего не удалит.
-- ═══════════════════════════════════════════════════════════════

-- (по желанию) посмотреть, сколько всего товаров сейчас:
-- select count(*) from catalog_products;

delete from catalog_products p
using (
  select id,
    row_number() over (
      partition by lower(btrim(replace(name, 'ё', 'е'))), coalesce(barcodes::text, '[]')
      order by (code is not null) desc, created_at asc, id asc
    ) as rn
  from catalog_products
) d
where p.id = d.id and d.rn > 1;

