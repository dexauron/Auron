// Отправка в WhatsApp — одно место на всё приложение

/* Сайт не может залезть в телефонную книжку: браузер её не отдаёт, и это
 * правильно. Но она и не нужна. Мы открываем WhatsApp с уже готовым текстом,
 * а список контактов и групп показывает он сам — человек выбирает кого угодно
 * и жмёт «Отправить». Работает и на телефоне, и на компьютере (WhatsApp Web).
 *
 * Если номер известен (поставщик, сам магазин) — открывается сразу нужная
 * переписка, искать в контактах не нужно.
 *
 * Раньше такие ссылки собирались руками в четырёх модулях, и номер в каждом
 * приводился к цифрам по-своему. Теперь это одна функция: ошибёшься — ошибка
 * будет одна и видна сразу. */

import { CFG } from './store.js';

/* Длиннее WhatsApp примет, но такое сообщение уже никто не читает: список
 * покупок на две сотни строк — это не список, а простыня. Хвост уходит в
 * ссылку, по ней виден весь список целиком. */
export const WA_MAX_LINES = 60;

/* «8 964 061-66-01», «+7 (964) 061-66-01», «9640616601» — всё это один номер.
 * Российскую восьмёрку меняем на семёрку, у номера без кода страны её
 * дописываем: WhatsApp принимает только полный международный номер. */
export function waDigits(phone) {
  let d = String(phone == null ? '' : phone).replace(/\D/g, '');
  if (d.length === 11 && d[0] === '8') d = '7' + d.slice(1);
  if (d.length === 10) d = '7' + d;
  return d.length >= 11 ? d : '';
}

// номер самого магазина — из настроек магазина, не зашит в коде
export const storeWa = () => waDigits(CFG.STORE_WHATSAPP);

// ссылка на переписку без текста — для строки «написать в WhatsApp»
export const waHref = (phone) => 'https://wa.me/' + waDigits(phone);

/* Отправить текст. Без номера WhatsApp сам спросит, кому. */
export function sendWhatsApp(text, phone) {
  const url = `https://wa.me/${waDigits(phone)}?text=${encodeURIComponent(text)}`;
  // всплывающие окна на телефоне иногда запрещены — тогда уходим прямо,
  // приложение всё равно откроется поверх, а каталог останется в истории
  const w = window.open(url, '_blank', 'noopener');
  if (!w) location.href = url;
}

/* Подпись магазина в конце сообщения. Список часто пересылают дальше — родне,
 * соседям, — и по этой строке видно, откуда он. Адрес и часы берутся из
 * настроек магазина: в другом магазине будут свои. */
export function storeSignature() {
  return [CFG.STORE_NAME, CFG.STORE_ADDRESS, CFG.STORE_HOURS].filter(Boolean).join(' · ');
}
