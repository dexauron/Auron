// Знакомство упрощено: без тарифов и без выбора типа бизнеса.
// Решение владельца: все функции доступны всем и бесплатно, а человек,
// открывший программу впервые, ещё не знает, что ему выбирать.
var fs=require('fs'), path=require('path');
var html=fs.readFileSync(path.join(__dirname,'..','Index.html'),'utf8');
var ok=0,fail=0;
function t(n,c,x){if(c){ok++;console.log('  ✓ '+n);}else{fail++;console.log('  ✗ '+n+(x?' → '+x:''));}}

var steps=html.match(/var OB_STEPS=\[[\s\S]*?\];/)[0];
var ids=(steps.match(/id:'[a-z]+'/g)||[]).map(function(s){return s.slice(4,-1);});

// ── Шаги ─────────────────────────────────────────────────────────────
t('шагов стало четыре', ids.length===4, ids.join(','));
t('порядок: приветствие → магазин → команда → готово',
  ids.join(',')==='welcome,company,roles,done', ids.join(','));
t('шага «тариф» больше нет', ids.indexOf('plan')<0);
t('шага «тип бизнеса» больше нет', ids.indexOf('type')<0);
t('шага «модули» больше нет', ids.indexOf('modules')<0);

// ── Ничего платного не осталось ──────────────────────────────────────
t('нет цены 990 ₽', html.indexOf('990 ₽')<0);
t('нет экрана «Выберите тариф»', html.indexOf('Выберите тариф')<0);
t('возможности не помечены как платные', !/pro:true/.test(html));
t('тариф не вычисляется из выбранных возможностей', !/d\.plan=\(mods\./.test(html));
t('в итогах написано, что всё бесплатно', /все функции, бесплатно/.test(html));

// ── Экран выбирается по имени, а не по номеру ────────────────────────
// Раньше был список по порядку: убрал шаг из середины — и все
// следующие экраны молча съезжают. Программа не падает, просто
// показывает не то, и заметить это можно только глазами.
t('экраны сопоставлены по имени шага',
  /var fns=\{welcome:App\._obStep0, company:App\._obStep2,/.test(html));
t('нет выбора экрана по номеру', !/fns=\[App\._obStep0,App\._obStep1/.test(html));
t('мёртвые экраны убраны',
  html.indexOf('_obStep1:function')<0 &&
  html.indexOf('_obStep3:function')<0 &&
  html.indexOf('_obStep5:function')<0);

// ── Первый шаг спрашивает только нужное ──────────────────────────────
var comp=html.slice(html.indexOf('_obStep2:function'), html.indexOf('_obStep4:function'));
t('спрашиваем имя', /Ваше имя/.test(comp));
t('спрашиваем название магазина', /Название магазина/.test(comp));
t('город больше не спрашиваем', !/Махачкала/.test(comp));
t('число точек больше не спрашиваем', !/Сколько точек/.test(comp));
t('дальше нельзя без названия',
  /canNext:function\(d\)\{return!!d\.company\.name\.trim\(\);\}/.test(steps));

// ── Знакомство не сжимается на компьютере ────────────────────────────
// Правило .screen>*{max-width:460px} я добавил для экранов входа, и оно
// сжало двухколоночное знакомство в нечитаемую полоску. По коду это
// было не видно — поймано снимком экрана.
t('знакомство исключено из ограничения ширины',
  /\.screen:not\(#scr-onboarding\)>\*\{max-width:460px/.test(html));
t('и кнопки тоже', /\.screen:not\(#scr-onboarding\)>button/.test(html));
t('старого правила без исключения нет', !/\n  \.screen>\*\{max-width:460px/.test(html));

// ── Приглашение сотрудников по ссылке осталось ───────────────────────
// Владелец создаёт магазин, сотрудники входят по его ссылке.
t('ссылка-приглашение обрабатывается', /__INVITE_ORG__/.test(html));
t('пришедший по ссылке не создаёт свой магазин',
  /if\(invNew\)\{App\._showJoin\(invNew\);return;\}/.test(html));

console.log('\nПростое знакомство: '+ok+' passed, '+fail+' failed');
process.exit(fail?1:0);
