// Названия по-человечески + один общий долг поставщикам + выходной день.
var fs=require('fs'), path=require('path');
var html=fs.readFileSync(path.join(__dirname,'..','Index.html'),'utf8');
var code=fs.readFileSync(path.join(__dirname,'..','Code.gs'),'utf8');
var ok=0,fail=0;
function t(n,c,x){if(c){ok++;console.log('  ✓ '+n);}else{fail++;console.log('  ✗ '+n+(x?' → '+x:''));}}

// ── Названия ─────────────────────────────────────────────────────────
// «Кассовое утро» и «Вечер — накладные» — про время суток, а не про суть.
// Владелец делает приём кассы утром, но по вчерашней смене; накладные —
// в любое время. Названия теперь описывают действие, а не час дня.
var GONE=['Кассовое утро','Вечер — накладные','Сколько наторговали',
          'Куда делись наличные','Приём торгового представителя'];
GONE.forEach(function(w){ t('убрано: «'+w+'»', html.indexOf(w)<0); });
var HAVE=['Приём кассы','Накладные за день','Выручка за смену',
          'Куда ушли наличные','Приём поставщика'];
HAVE.forEach(function(w){ t('есть: «'+w+'»', html.indexOf(w)>=0); });
t('в сверке «недостача» и «излишек», а не «не хватает/лишние»',
  /'Недостача ':'Излишек '/.test(html));
t('в вечере «оплатили», а не «отдали»',
  html.indexOf("'paid','Оплатили'")>=0 && html.indexOf("'paid','Отдали'")<0);
t('эмодзи убраны из заголовка экрана кассы',
  !/textContent=view==='morning'\?'🌅/.test(html));
t('в журнале сервера тоже новое название', /_log\(ss,'Накладные за день'/.test(code));

// ── Один долг вместо двух ────────────────────────────────────────────
// Это чинит нестыковку, которую я сам внёс в 5.7.0: вечер стал писать
// долг по каждому поставщику, а «Долг магазина» считал только особого
// контрагента и потому замер.
t('общий долг = сумма долгов поставщиков',
  /function getStoreDebt[\s\S]{0,900}if \(v>0\) \{ debt\+=v; parts\.push/.test(code));
t('переплата не уменьшает общий долг',
  /else if \(v<0\) over\+=-v;/.test(code));
t('переплата показана отдельно', /overpaid:over/.test(code));
t('разбивка по поставщикам отсортирована по сумме',
  /parts\.sort\(function\(a,b\)\{ return b\.debt-a\.debt; \}\)/.test(code));
t('история теперь по всем поставщикам',
  !/function getStoreDebtHistory[\s\S]{0,900}if \(String\(r\[D_REP-1\]\)!==STORE_DEBT_REP\) return;/.test(code));
t('строки начального остатка в историю не лезут',
  /function getStoreDebtHistory[\s\S]{0,900}indexOf\('OPEN:'\)>=0\) return;/.test(code));
t('служебный контрагент показан по-человечески',
  /\(nm===STORE_DEBT_REP\)\?'Общей суммой':nm/.test(code));
t('итог берётся из общего расчёта, а не из бегущего остатка',
  /cur=getStoreDebt\(\{ssId:p\.ssId\}\)/.test(code));
t('экран показывает «кому должны»', /Кому должны \('\+parts\.length/.test(html));
t('экран переименован в «Долг поставщикам»', /Долг поставщикам<\/div>|Долг поставщикам'/.test(html));
t('в настройках тоже', /Долг поставщикам и сверка/.test(html));
// Разницу сверки нельзя раскидывать по живым поставщикам: неизвестно,
// чей долг посчитан неверно, а угадывание испортит их карточки.
t('разница сверки идёт на служебного контрагента',
  /Разницу вешаем на служебного контрагента/.test(code));
t('владельцу это объяснено', /долги поставщиков не изменятся/.test(html));
t('история не грузит экран целиком', /items\.slice\(0,80\)/.test(html));

// ── Выходной день ────────────────────────────────────────────────────
// Без этого день без торговли просто выпадал, и средняя выручка за месяц
// получалась выше настоящей.
t('есть кнопка «не торговали»', /kNoTrade:async function/.test(html) && /Сегодня не торговали/.test(html));
t('пустая форма по-прежнему не сохраняется молча',
  /Введите суммы — или нажмите «Сегодня не торговали»/.test(html));
t('нулевой день проходит только по явной кнопке',
  /if\(!App\._kZeroDay&&!rec\.cashRev/.test(html));
t('флаг сбрасывается после записи', /App\._kZeroDay=false;/.test(html));
t('спрашиваем подтверждение', /kNoTrade[\s\S]{0,400}App\._confirm\(/.test(html));
t('владельцу сказано, что день останется в отчётах',
  /День останется в отчётах/.test(html));

console.log('\nНазвания, долг и выходной: '+ok+' passed, '+fail+' failed');
process.exit(fail?1:0);
