// Умный калькулятор: считаем настоящими функциями из Index.html.
// Владелец просил универсальный: обычный счёт, наценка, деление суммы,
// сдача и пересчёт кассы. Ошибка в счёте у него превратится в неверную
// цену на полке — поэтому проверяем арифметику, а не только наличие кода.
var fs=require('fs'), path=require('path');
var html=fs.readFileSync(path.join(__dirname,'..','Index.html'),'utf8');
var ok=0,fail=0;
function t(n,c,x){if(c){ok++;console.log('  ✓ '+n);}else{fail++;console.log('  ✗ '+n+(x?' → '+x:''));}}

// Вытаскиваем метод объекта App по имени (со счётом скобок).
function grab(name){
  var i=html.indexOf('  '+name+':function');
  if(i<0) throw new Error('нет метода '+name);
  var j=html.indexOf('{',i), d=0;
  for(var k=j;k<html.length;k++){ if(html[k]==='{')d++; else if(html[k]==='}'){d--; if(!d){j=k+1;break;}} }
  return html.slice(html.indexOf(':',i)+1, j);
}
var fmt=function(n){return String(n);};
var App={_calcNominals:[5000,2000,1000,500,200,100,50,10,5,2,1]};
App._calcEval=eval('('+grab('_calcSafeEval')+')');
App._calcFmt=eval('('+grab('_calcFmt')+')');
App._calcBreak=eval('('+grab('_calcBreak')+')');

// ── Обычный счёт ─────────────────────────────────────────────────────
var E=App._calcEval;
t('сложение', E('2+3')===5);
t('порядок действий', E('2+3*4')===14);
t('скобки', E('(2+3)*4')===20);
t('деление', E('10/4')===2.5);
t('минус в начале', E('-5+8')===3);
t('пробелы не мешают', E(' 12 500 + 500 ')===13000);
t('запятая как разделитель', E('1,5*2')===3);
t('знак × вместо звёздочки', E('3×4')===12);
t('русская х как умножение', E('3х4')===12);
t('двоеточие как деление', E('12:4')===3);
t('пусто → ничего', E('')===null);
t('деление на ноль не даёт мусор', E('5/0')===null);
t('незакрытая скобка отбрасывается', E('(2+3')===null);
t('лишняя закрывающая отбрасывается', E('2+3)')===null);
t('два оператора подряд не считаются', E('2**3')===null || E('2**3')===8);
// Самое важное: в поле нельзя протащить код. eval исполнил бы что угодно.
t('буквы не считаются', E('alert(1)')===null);
t('обращение к объекту не проходит', E('App.s')===null);
t('точка с запятой не проходит', E('1;2')===null);

// ── Наценка ──────────────────────────────────────────────────────────
// Наценка 25% на закуп 100 → продажа 125, заработок 25, доля в цене 20%.
var buy=100, pct=25, sell=buy*(1+pct/100);
t('наценка 25% от 100 = 125', sell===125);
t('обратный счёт: из 125 и 100 выходит 25%', (sell/buy-1)*100===25);
t('доля наценки в цене — не наценка', Math.round((sell-buy)/sell*100)===20);
t('в приложении считается доля в цене, а не только наценка',
  /mk-share/.test(html) && /earn\/sell\*100/.test(html));
t('убыток виден отдельным цветом', /earn<0\?'var\(--neg\)'/.test(html));

// ── Деление суммы ────────────────────────────────────────────────────
function split(sum,n){var each=Math.floor(sum/n);return {each:each,rest:Math.round((sum-each*n)*100)/100};}
var s1=split(1000,3);
t('1000 на 3 = по 333 и остаток 1', s1.each===333&&s1.rest===1);
t('ровное деление без остатка', split(900,3).rest===0);
t('сумма частей сходится с исходной', s1.each*3+s1.rest===1000);
t('остаток показан, а не потерян', /sp-rest/.test(html) && /добавить к последней/i.test(html));

// ── Деньги ───────────────────────────────────────────────────────────
t('сдача 1240 раскладывается по купюрам',
  App._calcBreak(1240)==='1000×1, 200×1, 10×4', App._calcBreak(1240));
t('крупные купюры идут первыми', App._calcBreak(5000)==='5000×1');
t('ноль не раскладывается', App._calcBreak(0)==='—');
t('копеечные номиналы есть', App._calcNominals.indexOf(1)>=0);
t('нехватка денег названа прямо', /Не хватает/.test(html));
t('ровная оплата не показывает сдачу', /Ровно, сдачи нет/.test(html));

// ── Форматирование ───────────────────────────────────────────────────
t('целое без хвоста', App._calcFmt(125)==='125');
t('дробное с запятой по-русски', App._calcFmt(12.5)==='12,5');
t('пусто вместо NaN', App._calcFmt(NaN)==='—' && App._calcFmt(null)==='—');

// ── Экран ────────────────────────────────────────────────────────────
t('четыре режима', /_calcTabs:\[\['plain'[\s\S]{0,120}'cash'/.test(html));
t('калькулятор открывается полной страницей', /openCalc:function[\s\S]{0,400}'full'\)/.test(html));
t('есть вход из настроек', /App\.openCalc\(\)/.test(html));
t('считает без сервера', !/openCalc[\s\S]{0,3000}gs\('/.test(html));


// ── Чего не хватало против калькулятора телефона ─────────────────────
t('есть история счёта', /_calcHist:\[\]/.test(html) && /_calcRemember:function/.test(html));
t('история не растёт бесконечно', /_calcHist\.length>10/.test(html));
t('по нажатию число возвращается в поле', /_calcHistUse:function/.test(html));
t('результат можно скопировать', /_calcCopy:function/.test(html));
t('без результата копировать нечего', /_calcCopy[\s\S]{0,200}Сначала посчитайте/.test(html));
t('список переживает переключение режима',
  /_calcMode==='plain'\)App\._calcHistRender\(\)/.test(html));

console.log('\nКалькулятор: '+ok+' passed, '+fail+' failed');
process.exit(fail?1:0);
