// Ввод сумм в кассе: разряды, выражения, сверка.
// Раньше поля были обычными числовыми: «137000» без пробелов. Ошибиться
// на ноль легко, а заметить — нет, и в отчёте это всплывёт через неделю.
var fs=require('fs'), path=require('path');
var html=fs.readFileSync(path.join(__dirname,'..','Index.html'),'utf8');
var ok=0,fail=0;
function t(n,c,x){if(c){ok++;console.log('  ✓ '+n);}else{fail++;console.log('  ✗ '+n+(x?' → '+x:''));}}
function grab(name){
  var i=html.indexOf('  '+name+':function');
  if(i<0) throw new Error('нет метода '+name);
  var j=html.indexOf('{',i), d=0;
  for(var k=j;k<html.length;k++){ if(html[k]==='{')d++; else if(html[k]==='}'){d--; if(!d){j=k+1;break;}} }
  return html.slice(html.indexOf(':',i)+1, j);
}
var App={};
App._calcSafeEval=eval('('+grab('_calcSafeEval')+')');
App._mnum=eval('('+grab('_mnum')+')');
App._mfmt=eval('('+grab('_mfmt')+')');

// ── Разряды ──────────────────────────────────────────────────────────
t('137000 → 137 000', App._mfmt(137000)==='137 000', App._mfmt(137000));
t('тысяча без хвоста', App._mfmt(1000)==='1 000');
t('сотни не разбиваются', App._mfmt(999)==='999');
t('миллион разбит дважды', App._mfmt(2531682)==='2 531 682', App._mfmt(2531682));
t('ноль остаётся нулём', App._mfmt(0)==='0');
t('дробное округляется', App._mfmt(1250.6)==='1 251');

// ── Чтение обратно ───────────────────────────────────────────────────
t('пробелы не мешают прочитать', App._mnum('137 000')===137000);
t('неразрывный пробел тоже', App._mnum('137 000')===137000);
t('запятая как разделитель дробной', App._mnum('1,5')===1.5);
t('пусто = ноль', App._mnum('')===0);
t('мусор = ноль, а не NaN', App._mnum('абв')===0);
t('null не роняет', App._mnum(null)===0);
t('число проходит как есть', App._mnum(4200)===4200);

// Владелец считает в уме прямо в поле — это уже было на клавиатуре,
// нельзя было потерять при переходе на форматированные поля.
t('выражение складывается', App._mnum('1000+500')===1500);
t('выражение с пробелами', App._mnum('12 000 + 3 000')===15000);
t('умножение', App._mnum('3*250')===750);
t('минус в начале — это число, а не действие', App._mnum('-500')===-500);

// Круг: ввели → отформатировали → прочитали. Не должно ничего терять.
[0,1,999,1000,137000,2531682,9905373].forEach(function(n){
  t('туда-обратно '+n, App._mnum(App._mfmt(n))===n, App._mfmt(n));
});

// ── Разметка ─────────────────────────────────────────────────────────
var moneyIds=['kz-cash-rev','kz-cash-supp','kz-cash-collect','kz-cash-left',
              'k-balance','ki-cash','ki-repaid','ki-new'];
moneyIds.forEach(function(id){
  var re=new RegExp('<input type="text" class="money" id="'+id+'"');
  t('поле '+id+' денежное', re.test(html));
});
t('каналы безнала тоже денежные', /class="money kz-ch"/.test(html));
t('старых числовых полей кассы не осталось',
  !/<input type="number" id="(kz-|ki-|k-balance)/.test(html));

// ── Чтение значений в расчётах ───────────────────────────────────────
// Самое опасное место: если где-то остался parseFloat, «137 000»
// прочитается как 137 — и в базу уйдёт сумма в тысячу раз меньше.
t('сверка читает через общий разбор', /_kReconcile:function\(\)\{\s*var g=App\._mval;/.test(html));
t('сохранение кассы читает через общий разбор',
  /var g=App\._mval;\s*\/\/ Безнал/.test(html));
t('каналы безнала читаются через общий разбор',
  /var amt=App\._mval\(inp\);/.test(html));
t('накладные читаются через общий разбор',
  /cash=App\._mval\('ki-cash'\)/.test(html) && /cashPaid:App\._mval\('ki-cash'\)/.test(html));
t('нигде не осталось parseFloat по этим полям',
  !/parseFloat\((document\.getElementById\('(kz-|ki-|k-balance)|inp\.value\)\|\|0\).{0,20}kz)/.test(html));

// ── Сверка: главный ответ утра ───────────────────────────────────────
t('ответ подаётся словами, а не знаком', /Не хватает |Лишние |Сходится/.test(html));
t('до заполнения не пугаем цветом', /var touched=rev>0\|\|got>0;/.test(html));
t('сошлось — зелёный блок, нет — красный',
  /'k-recon'\+\(!touched\?'':\(diff===0\?' ok':' bad'\)\)/.test(html));
t('видно обе суммы: выручка и разложено',
  /Выручка наличными.{0,120}kz-should/.test(html) && /Разложено.{0,80}kz-got/.test(html));
t('размер ответа крупнее остального текста', /\.k-recon-v\{font-size:26px/.test(html));

// ── Порядок и подписи ────────────────────────────────────────────────
// Кассир читает Z-отчёт сверху вниз: выручка, потом безнал. Раньше
// безнал стоял в самом конце, после «куда делись деньги».
t('безнал идёт сразу за наличной выручкой',
  html.indexOf('Сколько наторговали')<html.indexOf('Куда делись наличные'));
t('подписи короткие, пояснения отдельно', /class="k-help"/.test(html));
t('выручка — самое крупное поле ввода', /\.k-big input\{font-size:20px/.test(html));
t('цифры не пляшут по ширине', /input\.money\{font-variant-numeric:tabular-nums;\}/.test(html));

console.log('\nВвод сумм в кассе: '+ok+' passed, '+fail+' failed');
process.exit(fail?1:0);
