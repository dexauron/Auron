/* ============================================================================
   ПОИСК, КОТОРЫЙ ОТВЕЧАЕТ

   Владелец сказал: «Сколько я должен Молокозаводу», «расходы за июль»,
   «недостачи Ани» — и чтобы ответ был строкой, а не экраном, по которому
   ещё надо искать глазами.

   До этого строка поиска вверху вела в никуда: набираешь — и оказываешься
   на Пульте. Экрана с таким именем в программе не было вовсе.

   ЧТО ЭТОТ МОДУЛЬ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ. Он не «понимает язык». Он
   разбирает вопрос на три части — о ЧЁМ спрашивают, про КОГО и за КАКОЙ
   СРОК, — и считает ответ теми же функциями, что считают экраны. Никакой
   своей арифметики здесь нет и быть не должно: иначе поиск однажды ответит
   одно, а экран покажет другое, и верить будет нечему.

   Не понял вопрос — так и говорит. Молча показать не то хуже, чем честно
   сказать «не понял»: неверному ответу поверят.
   ========================================================================== */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.WMAsk = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  var МЕСЯЦЫ = ['январ', 'феврал', 'март', 'апрел', 'мая|май', 'июн', 'июл',
    'август', 'сентябр', 'октябр', 'ноябр', 'декабр'];

  function норм(s) {
    return String(s == null ? '' : s).toLowerCase().replace(/ё/g, 'е').trim();
  }

  /* --- ЗА КАКОЙ СРОК СПРАШИВАЮТ --------------------------------------------
     Срок в вопросе может быть назван словом («за июль», «вчера», «за год»)
     или не назван вовсе. Не назван — значит «за всё время»: владелец,
     спрашивая «сколько должен Молокозаводу», имеет в виду весь долг, а не
     долг за сегодня. */
  function срок(q, E) {
    var t = E.today(), год = +t.slice(0, 4);

    if (/(^|[^а-я])сегодня/.test(q)) return { от: t, до: t, имя: 'сегодня' };
    if (/(^|[^а-я])вчера/.test(q)) {
      var в = E.addDays(t, -1);
      return { от: в, до: в, имя: 'вчера' };
    }
    if (/за неделю|за 7 дней|неделю/.test(q)) {
      return { от: E.addDays(t, -6), до: t, имя: 'за неделю' };
    }
    if (/этот месяц|за месяц|в этом месяце/.test(q)) {
      return { от: t.slice(0, 7) + '-01', до: t, имя: 'за этот месяц' };
    }
    if (/за год|в этом году|за этот год/.test(q)) {
      return { от: год + '-01-01', до: t, имя: 'за ' + год + ' год' };
    }

    /* Про \b и кириллицу. В JavaScript граница слова считается по латинице:
       между пробелом и русской буквой границы НЕТ, потому что обе для
       регулярки «не буквы». Поэтому «\bиюл» не находило слово «июль» — и
       весь разбор месяца молча не работал, а ответ приходил «за всё время».
       Ищем по началу слова сами: начало строки или не-буква перед основой. */
    for (var i = 0; i < МЕСЯЦЫ.length; i++) {
      if (!new RegExp('(^|[^а-я])(' + МЕСЯЦЫ[i] + ')').test(q)) continue;
      /* Год в вопросе называют редко. Если названный месяц ещё не наступил,
         владелец почти наверняка имеет в виду прошлый год: в марте «за
         декабрь» — это прошлый декабрь, а не тот, что будет. */
      var г = год;
      var явный = q.match(/(20\d\d)/);
      if (явный) г = +явный[1];
      else if (i + 1 > +t.slice(5, 7)) г = год - 1;
      var мм = ('0' + (i + 1)).slice(-2);
      var последний = new Date(г, i + 1, 0).getDate();
      return { от: г + '-' + мм + '-01', до: г + '-' + мм + '-' + последний,
        имя: 'за ' + названиеМесяца(i) + ' ' + г };
    }
    return { от: '', до: '', имя: 'за всё время' };
  }

  function названиеМесяца(i) {
    return ['январь', 'февраль', 'март', 'апрель', 'май', 'июнь', 'июль',
      'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь'][i];
  }

  /* --- ПРО КОГО СПРАШИВАЮТ -------------------------------------------------
     Имена берём из справочников самой базы, а не из списка в коде: в каждом
     магазине свои поставщики и свои кассиры. Ищем самое длинное совпадение —
     иначе «Молочный дом» нашёлся бы как «Молоко». */
  /* Основа слова: отбрасываем окончание. Русский падеж меняет хвост —
     «Аня → Ани → Ане», «Молокозавод → Молокозаводу». Отбрасывать хвост
     целиком нельзя: останется «ан», и «Аня» перепутается с «Антоном».
     Поэтому снимаем только гласные с конца, не больше двух. */
  function основа(w) {
    var s2 = w;
    for (var i = 0; i < 2 && s2.length > 2; i++) {
      if ('аеиоуыэюяй'.indexOf(s2.charAt(s2.length - 1)) < 0) break;
      s2 = s2.slice(0, -1);
    }
    return s2;
  }

  function слова(s2) {
    return норм(s2).split(/[^a-zа-я0-9]+/).filter(function (w) { return w.length > 1; });
  }

  /* Про КОГО спрашивают. Имена берём из справочников самой базы, а не из
     списка в коде: в каждом магазине свои поставщики и свои кассиры.

     Сначала ищем точное совпадение основ — «Ани» и «Аня» дают одну основу
     «ан». Только если точного нет, разрешаем совпадение по началу: так
     «Хлебозаводом» находит «Хлебозавод», но «Ани» не превращается в
     «Антона». Порядок здесь и есть вся хитрость. */
  function кто(q, список) {
    var вопрос = слова(q).map(основа);
    var точно = null, поНачалу = null;
    (список || []).forEach(function (имя) {
      var части = слова(имя).map(основа);
      if (!части.length) return;
      var всеТочно = true, всеПоНачалу = true;
      части.forEach(function (ч) {
        if (ч.length < 2) { всеТочно = false; всеПоНачалу = false; return; }
        var естьТочно = false, естьПоНачалу = false;
        вопрос.forEach(function (в) {
          if (в === ч) естьТочно = true;
          if (ч.length >= 4 && (в.indexOf(ч) === 0 || ч.indexOf(в) === 0) &&
              Math.min(в.length, ч.length) >= 4) естьПоНачалу = true;
        });
        if (!естьТочно) всеТочно = false;
        if (!естьТочно && !естьПоНачалу) всеПоНачалу = false;
      });
      if (всеТочно && (!точно || имя.length > точно.length)) точно = имя;
      else if (всеПоНачалу && (!поНачалу || имя.length > поНачалу.length)) поНачалу = имя;
    });
    return точно || поНачалу;
  }

  /* --- ОТВЕТ ---------------------------------------------------------------
     Каждый разбор возвращает одно и то же: крупное число, подпись под ним и
     куда пойти смотреть подробности. */
  function ответ(о) {
    return { есть: true, заголовок: о.заголовок, число: о.число,
      подпись: о.подпись || '', go: о.go || '', форма: о.форма || '',
      деньги: о.деньги !== false };
  }

  /* Считать сами мы ничего не умеем и не должны: берём у движка ровно те
     функции, которыми считают экраны. */
  function спросить(вопрос, S, E, Q) {
    var q = норм(вопрос);
    if (!q || q.length < 3) return { есть: false };

    var st = S.state || {}, наст = S.settings || {};
    var rows = st.dds || [], счета = st.accounts || [];
    var с = срок(q, E);
    var вПериод = function (r) {
      var d = E.txt(r.date);
      if (с.от && d < с.от) return false;
      if (с.до && d > с.до) return false;
      return true;
    };
    var отобранные = с.от || с.до ? rows.filter(вПериод) : rows;

    var спр = Q && Q.dicts ? Q.dicts(st, наст) : {};
    /* Поставщиков берём и из справочника, и из плана выплат: в магазине,
       где долг ведут одной суммой, поставщик попадает в базу только через
       запланированную выплату, и в справочнике его нет. */
    var поставщики = (спр.suppliers || []).map(function (x) { return x.name || x; });
    (st.plans || []).forEach(function (p) {
      var имя = E.txt(p.supplier);
      if (имя && поставщики.indexOf(имя) < 0) поставщики.push(имя);
    });
    var кассиры = (спр.cashiers || []).map(function (x) { return x.name || x; });
    var люди = (st.staff || []).map(function (x) { return x.name; });

    /* --- СКОЛЬКО ДОЛЖЕН ПОСТАВЩИКУ ------------------------------------- */
    if (/должен|должны|долг/.test(q) && !/мне|покупател|клиент/.test(q)) {
      var п = кто(q, поставщики);
      if (п) {
        var план = (st.plans || []).filter(function (x) {
          return норм(x.supplier) === норм(п) && E.txt(x.status) !== 'Оплачена' &&
            E.txt(x.status) !== 'Отменена';
        });
        var сумма = план.reduce(function (a, x) { return a + E.safeRound(x.amount); }, 0);
        return ответ({
          заголовок: 'Запланировано заплатить: ' + п,
          число: E.safeRound(сумма),
          подпись: план.length
            ? план.length + ' ' + E.plural(план.length, 'выплата', 'выплаты', 'выплат') +
              '. Общий долг магазина ведётся одной суммой, по именам его не разложить — ' +
              'это то, что вы сами запланировали этому поставщику.'
            : 'Выплат этому поставщику не запланировано. Общий долг магазина — ' +
              E.fmtMoney(E.supplierDebt(rows, наст).debt) + ', но он ведётся одной суммой.',
          go: 'finpay' });
      }
      var долг = E.supplierDebt(rows, наст);
      return ответ({ заголовок: 'Должны поставщикам', число: долг.debt,
        подпись: 'общей суммой по магазину', go: 'suppliers' });
    }

    /* --- НЕДОСТАЧИ ЧЕЛОВЕКА -------------------------------------------- */
    if (/недостач|не сошл|расхожден/.test(q)) {
      var к = кто(q, кассиры.concat(люди));
      var рейтинг = E.cashierRating(отобранные);
      if (к) {
        var его = рейтинг.filter(function (r) { return норм(r.name) === норм(к); })[0];
        if (!его) {
          return ответ({ заголовок: 'Недостачи: ' + к, число: 0,
            подпись: 'у этого человека ' + с.имя + ' смен не было', go: 'cashiers' });
        }
        return ответ({ заголовок: 'Недостачи: ' + к, число: его.short,
          подпись: с.имя + ' · ' + его.shifts + ' ' +
            E.plural(его.shifts, 'смена', 'смены', 'смен') + ', из них с расхождением ' +
            его.badShifts + '. На 1000 ₽ выручки — ' + E.fmtMoney(его.per1000),
          go: 'cashiers' });
      }
      var всего = E.totals(отобранные);
      return ответ({ заголовок: 'Недостачи по кассе', число: всего.short,
        подпись: с.имя + ' · ' + всего.badShifts + ' смен с расхождением из ' + всего.shifts,
        go: 'cashiers' });
    }

    /* --- РАСХОДЫ -------------------------------------------------------- */
    if (/расход|потратил|трат|затрат/.test(q)) {
      var т = E.totals(отобранные);
      var статьи = Object.keys(т.byCategory || {}).map(function (k) {
        return { name: k, sum: т.byCategory[k] };
      }).sort(function (a, b) { return b.sum - a.sum; });
      return ответ({ заголовок: 'Расходы', число: т.expense,
        подпись: с.имя + (статьи.length
          ? ' · больше всего: ' + статьи[0].name + ' — ' + E.fmtMoney(статьи[0].sum) : ''),
        go: 'ledger' });
    }

    /* --- ВЫРУЧКА -------------------------------------------------------- */
    if (/выручк|заработал|продал|оборот/.test(q)) {
      var в = E.totals(отобранные);
      return ответ({ заголовок: 'Выручка', число: в.revenue,
        подпись: с.имя + ' · наличными ' + E.fmtMoney(в.zCash) +
          ', безналом ' + E.fmtMoney(в.zCashless),
        go: 'finreport' });
    }

    /* --- СКОЛЬКО ДЕНЕГ СЕЙЧАС ------------------------------------------- */
    if (/сколько денег|в сейфе|на счет|наличн|остаток/.test(q)) {
      var б = E.accountBalances(rows, счета);
      var сейф = б.totals.cash, счёт = б.totals.bank;
      if (/на счет|безнал/.test(q)) {
        return ответ({ заголовок: 'На счёте', число: счёт,
          подпись: 'карта, СБП, переводы', go: 'pulse' });
      }
      if (/в сейфе|наличн/.test(q)) {
        return ответ({ заголовок: 'В сейфе', число: сейф,
          подпись: 'наличные у вас на руках', go: 'pulse' });
      }
      return ответ({ заголовок: 'Всего денег', число: E.safeRound(сейф + счёт),
        подпись: 'в сейфе ' + E.fmtMoney(сейф) + ', на счёте ' + E.fmtMoney(счёт),
        go: 'pulse' });
    }

    /* --- ПРИБЫЛЬ -------------------------------------------------------- */
    if (/прибыл|заработали чистыми|чистыми/.test(q)) {
      var месяц = (с.от || E.today()).slice(0, 7);
      return ответ({ заголовок: 'Прибыль', число: null,
        подпись: 'Прибыль считается за месяц целиком — откройте «Прибыль (P&L)» ' +
          'за ' + месяц + '.', go: 'pnl' });
    }

    /* --- СКОЛЬКО ДОЛЖНЫ ЧЕЛОВЕКУ --------------------------------------- */
    if (/должен|должны/.test(q)) {
      var ч = кто(q, люди);
      if (ч) {
        var в2 = E.payrollSummary(
          (st.timesheet || []).filter(вПериод), (st.payouts || []).filter(вПериод),
          st.staff || [], наст, { dds: отобранные });
        var стр = (в2.rows || в2).filter(function (r) { return норм(r.employee) === норм(ч); })[0];
        if (стр) {
          return ответ({ заголовок: 'Должны ' + ч, число: стр.left,
            подпись: с.имя + ' · начислено ' + E.fmtMoney(стр.accrued) +
              ', выдано ' + E.fmtMoney(стр.paid), go: 'payroll' });
        }
      }
    }

    return { есть: false };
  }

  return { спросить: спросить, срок: срок, кто: кто, норм: норм };
});
