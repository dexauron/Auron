/* ============================================================================
   ЦЕНТР УВЕДОМЛЕНИЙ

   Владелец сказал точно: программа должна стать умнее — подсказывать, что
   важно сегодня, предупреждать заранее, замечать странное. И сразу же:
   «но чтобы это было в уведомлениях, а не на виду».

   Это одна из тех просьб, которые легко сделать наоборот. Умная программа
   так и норовит вывалить всё, что заметила, на главный экран — и человек
   перестаёт читать вообще. Поэтому здесь два потока:

   СРОЧНОЕ — прорывается на экран полосой сверху. Ровно три вещи, которые
   назвал владелец, и ни одной сверх:
       · записи перестали сохраняться;
       · крупная недостача прямо сейчас, пока кассир ещё здесь;
       · сегодня надо платить поставщику.

   ОСТАЛЬНОЕ — живёт в колокольчике. Никогда не лезет на экран само.

   Правило для того, кто будет править дальше: НОВОЕ УВЕДОМЛЕНИЕ ПО
   УМОЛЧАНИЮ НЕ СРОЧНОЕ. Список срочного задан владельцем, и расширять его
   без его слова нельзя — иначе полоса опять станет шумом.
   ========================================================================== */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.WMNotices = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  function num(E, v) { return E.num(v); }

  /* Собрать все уведомления. Возвращает список, уже разложенный по важности:
     'срочно' — на полосу, 'внимание' и 'кстати' — только в колокольчик. */
  function собрать(S, E, REV) {
    var st = S.state || {}, наст = S.settings || {};
    var rows = st.dds || [], счета = st.accounts || [];
    var сегодня = E.today();
    var out = [];

    function добавить(вид, id, icon, text, why, куда) {
      out.push({ вид: вид, id: id, icon: icon, text: text, why: why || '',
        go: (куда && куда.go) || '', form: (куда && куда.form) || '',
        act: (куда && куда.act) || 'Открыть' });
    }

    /* --- СРОЧНОЕ (три вещи, названные владельцем) ---------------------- */

    if (S.lastSaveError) {
      добавить('срочно', 'save', 'warning',
        'ЗАПИСИ НЕ СОХРАНЯЮТСЯ: ' + S.lastSaveError,
        'Подключите папку на экране «Данные и копии» — там места хватит. ' +
        'Пока это не сделано, всё, что вы вписываете, может пропасть.',
        { go: 'data', act: 'Исправить' });
    }

    var план = E.planTotals(st.plans || [], сегодня);
    if (план.overdue) {
      добавить('срочно', 'overdue', 'warning',
        'Просрочены выплаты на ' + E.fmtMoney(план.overdue),
        'Эти деньги надо было отдать раньше.', { go: 'finpay', act: 'Платить' });
    }
    if (план.dueToday) {
      добавить('срочно', 'duetoday', 'calendar',
        'Сегодня платить ' + E.fmtMoney(план.dueToday),
        '', { go: 'finpay', act: 'Платить' });
    }

    /* Крупная недостача ПРЯМО СЕЙЧАС — то есть по вчерашней или сегодняшней
       смене, пока кассир ещё рядом и помнит, что брал. Недостача недельной
       давности срочной уже не является: разбираться с ней поздно, и место
       ей в колокольчике. */
    var порог = num(E, наст.diffCrit) || 1000;
    var свежие = E.shiftsOf(rows, null, наст).filter(function (r) {
      return E.daysBetween(r.date, сегодня) <= 1 &&
        Math.abs(E.shiftCalc(r).diff) >= порог;
    });
    if (свежие.length) {
      var с = E.shiftCalc(свежие[свежие.length - 1]);
      добавить('срочно', 'freshdiff', 'warning',
        (с.diff < 0 ? 'Недостача ' : 'Излишек ') + E.fmtMoney(Math.abs(с.diff)) +
          ' по последней смене',
        'Кассир ещё помнит, что брал. Завтра выяснять будет не у кого.',
        { go: 'cashiers', act: 'Разобрать' });
    }

    /* --- ВНИМАНИЕ: предупреждаем ЗАРАНЕЕ ------------------------------- */

    /* Самая частая причина, по которой магазин остаётся без денег: выручка
       была, её пустили на товар, а в конце месяца пришли аренда и зарплата.
       Считаем по нынешнему темпу — успеем накопить или нет. */
    var постоянные = S.fixedMonthly ? S.fixedMonthly() : 0;
    if (постоянные > 0) {
      var день = +сегодня.slice(8, 10);
      var вМесяце = new Date(+сегодня.slice(0, 4), +сегодня.slice(5, 7), 0).getDate();
      var осталосьДней = вМесяце - день;
      if (осталосьДней >= 1 && осталосьДней <= 14) {
        var наличные = E.cashOnHand(rows, наст, null, счета);
        var б = E.accountBalances(rows, счета);
        var всего = E.safeRound(наличные + б.totals.bank);
        if (всего < постоянные) {
          добавить('внимание', 'fixed', 'calendar',
            'Через ' + осталосьДней + ' ' + E.plural(осталосьДней, 'день', 'дня', 'дней') +
              ' платить ' + E.fmtMoney(постоянные) + ', а есть ' + E.fmtMoney(всего),
            'Не хватает ' + E.fmtMoney(E.safeRound(постоянные - всего)) + '. ' +
            'Это аренда, зарплата, налоги и прочее постоянное — их платят независимо ' +
            'от того, как шла торговля.',
            { go: 'funds', act: 'Посмотреть' });
        }
      }
    }

    /* Долг поставщикам подошёл к порогу, который владелец сам назвал */
    var долг = E.supplierDebt(rows, наст);
    var критДолг = num(E, наст.debtCrit);
    if (критДолг && долг.debt >= критДолг) {
      добавить('внимание', 'debt', 'clipboard',
        'Долг поставщикам ' + E.fmtMoney(долг.debt),
        'Это выше порога, который вы задали в настройках.',
        { go: 'suppliers', act: 'Посмотреть' });
    }

    /* Наличных скопилось больше, чем вы считаете нужным держать */
    var лимит = num(E, наст.cashLimit);
    if (лимит) {
      var нал = E.cashOnHand(rows, наст, null, счета);
      if (нал > лимит) {
        добавить('внимание', 'cashlimit', 'banknote',
          'Наличных ' + E.fmtMoney(нал) + ' — больше вашего порога',
          'Держать дома или в сейфе больше нужного рискованно. ' +
          'Обычно лишнее отвозят в банк.', { form: 'moveCash', act: 'Отвезти' });
      }
    }

    /* Смена за вчера не сведена */
    var вчера = E.addDays(сегодня, -1);
    if (rows.length && !E.shiftsOf(rows, null, наст).some(function (r) { return r.date === вчера; })) {
      добавить('внимание', 'noshift', 'calculator',
        'Смена за ' + вчера.slice(8, 10) + '.' + вчера.slice(5, 7) + ' не сведена',
        'Чем позже сводить, тем труднее вспомнить, что было.',
        { form: 'shiftClose', act: 'Свести' });
    }

    /* --- ЗАМЕЧАТЬ СТРАННОЕ: это умеет Ревизор -------------------------- */

    if (REV && REV.check) {
      var найдено = REV.check(st, наст);

      /* ОДНОРОДНЫЕ НАХОДКИ СВОРАЧИВАЕМ В ОДНУ СТРОКУ.
         За год Ревизор находит, скажем, четыре недостачи по разным сменам —
         и все четыре ложатся в колокольчик одинаковыми строками. Это ровно
         то, на что жаловался владелец: «куча информации перед глазами, и
         фокус теряется». Показываем первую, а про остальные говорим числом;
         сами они никуда не делись — кнопка ведёт к ним в Ревизор.

         Вид находки — это начало её номера: «diff:», «collect:», «own:».
         Без двоеточия номер сам по себе и есть вид. */
      var поВидам = {}, порядок = [];
      (найдено.findings || []).forEach(function (f, i) {
        var вид = E.txt(f.key || i).split(':')[0];
        if (!поВидам[вид]) { поВидам[вид] = []; порядок.push(вид); }
        поВидам[вид].push(f);
      });

      порядок.forEach(function (вид) {
        var свои = поВидам[вид], f = свои[0], ещё = свои.length - 1;
        var хвост = ещё > 0 ? ' Остальные ' + ещё + ' — в Ревизоре.' : '';
        /* Ревизор уже разложил находки по важности. Его «тревоги» кладём во
           «внимание», а не в «срочно»: срочное задано владельцем списком из
           трёх вещей, и разрастаться этот список сам по себе не должен. */
        добавить(f.level === 'alarm' ? 'внимание' : 'кстати',
          'rev' + вид + (ещё ? ':' + свои.length : ''),
          f.level === 'alarm' ? 'warning' : 'info',
          f.title + (ещё > 0 ? ' и ещё ' + ещё + ' ' +
            E.plural(ещё, 'похожая', 'похожие', 'похожих') : ''),
          (f.why || '') + хвост, { go: f.go || 'revizor', act: 'Разобрать' });
      });
    }

    return out;
  }

  /* --- ЧТО ИЗ ЭТОГО НОВОЕ ------------------------------------------------
     Значок с числом должен показывать НЕПРОЧИТАННОЕ, иначе он горит всегда
     и перестаёт что-либо значить. Прочитанное помним по номеру уведомления:
     по дате нельзя, одно и то же дело живёт неделями. */
  function прочитанные(S, E) {
    return E.txt(S.settings && S.settings.noticeSeen).split('|').filter(Boolean);
  }

  function новых(список, S, E) {
    var видели = прочитанные(S, E);
    var n = 0;
    (список || []).forEach(function (x) {
      if (x.вид === 'кстати') return;          // «кстати» значок не зажигает
      if (видели.indexOf(x.id) < 0) n++;
    });
    return n;
  }

  function пометить(список, S, E) {
    var было = прочитанные(S, E);
    (список || []).forEach(function (x) { if (было.indexOf(x.id) < 0) было.push(x.id); });
    /* Список не должен расти вечно: держим последние двести номеров.
       Уведомление, о котором забыли через двести других, всё равно
       покажется снова — и это не беда. */
    if (было.length > 200) было = было.slice(было.length - 200);
    S.setSetting('noticeSeen', было.join('|'));
  }

  function срочные(список) {
    return (список || []).filter(function (x) { return x.вид === 'срочно'; });
  }

  return { собрать: собрать, новых: новых, пометить: пометить,
    срочные: срочные, прочитанные: прочитанные };
});
