/* ============================================================================
   ГОД РАБОТЫ МАГАЗИНА. Запуск:  node tests/проверка-года.js [зерно]

   Владелец попросил: «сделай тест, как будто работает год в приложении,
   проверь всё». Здесь именно это: 365 дней записей, какие он делал бы сам,
   а потом сверка всего, что программа насчитала.

   ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: правду считает САМ ТЕСТ, а не программа.
   Он сам кладёт деньги в сейф и сам их оттуда достаёт, ведя свой счёт на
   бумаге. Потом спрашивает программу — и сравнивает. Проверка, которая
   берёт ответ у проверяемого, не проверяет ничего: за эту работу я такое
   уже писал, и оно проходило при сломанном коде.

   Деньги считаем В КОПЕЙКАХ целыми числами — чтобы своя арифметика не
   накопила той самой ошибки, которую ищем.
   ========================================================================== */
const path = require('path');
const WM = require(path.join(__dirname, '..', 'js', 'engine.js'));

let passed = 0, failed = 0;
function check(name, ok, got, want) {
  if (ok) { passed++; console.log('  ✅ ' + name + (got !== undefined ? '  → ' + got : '')); }
  else { failed++; console.log('  ❌ ' + name + '  получено: ' + got + ', ожидалось: ' + want); }
}
function руб(коп) { return Math.round(коп) / 100; }

/* Свой генератор случайных чисел: при одном зерне год получается тот же.
   Нашлась ошибка — её можно воспроизвести, а не ловить заново. */
const ЗЕРНО = Number(process.argv[2]) || 20260918;
let семя = ЗЕРНО;
function сл() { семя = (семя * 1103515245 + 12345) & 0x7fffffff; return семя / 0x7fffffff; }
function цел(a, b) { return a + Math.floor(сл() * (b - a + 1)); }

const КАССЫ = ['Касса 1', 'Касса 2'];
const СМЕНЫ = ['День', 'Ночь'];
const КАССИРЫ = ['Аня', 'Марат', 'Зарема', 'Иман'];
const СТАТЬИ = ['Аренда', 'Коммунальные', 'Интернет и связь', 'Охрана',
  'Вывоз мусора', 'Обед', 'Расходники', 'Ремонт и обслуживание'];
const ПОСТАВЩИКИ = ['Молокозавод', 'Хлебозавод', 'Мясокомбинат', 'Овощебаза', 'Напитки'];

const счета = [
  { id: 'сейф', name: 'Сейф', kind: 'cash', opening: 0, defaultCash: true },
  { id: 'банк', name: 'Расчётный счёт', kind: 'bank', opening: 0, defaultCashless: true }
];
const НАЧАЛЬНЫЙ_СЕЙФ = 150000;
счета[0].opening = НАЧАЛЬНЫЙ_СЕЙФ;
const settings = { openSafeStart: НАЧАЛЬНЫЙ_СЕЙФ, tills: КАССЫ.join(', '),
  finShifts: СМЕНЫ.join(', '), ownFunds: 'да' };

/* --- Своя бухгалтерия на бумаге ----------------------------------------- */
let сейфКоп = Math.round(НАЧАЛЬНЫЙ_СЕЙФ * 100);
let банкКоп = 0;
let выручкаКоп = 0;         // вся выручка: нал + безнал, до возвратов
let своиВнёсКоп = 0, своиЗабралКоп = 0;
let недостачиКоп = 0, излишкиКоп = 0;
const rows = [];
let n = 0;
function id() { return 'r' + (++n); }

function дата(д) {
  const t = new Date(Date.UTC(2026, 0, 1));
  t.setUTCDate(t.getUTCDate() + д);
  return t.toISOString().slice(0, 10);
}

/* Размен по каждой кассе: сколько там оставили в прошлый раз */
const разменКоп = {};
КАССЫ.forEach(function (k) { разменКоп[k] = 500000; });   // 5 000 ₽

for (let д = 0; д < 365; д++) {
  const дт = дата(д);

  for (const касса of КАССЫ) {
    for (const смена of СМЕНЫ) {
      const было = разменКоп[касса];
      const zНалКоп = цел(2000000, 12000000);            // 20 000 – 120 000 ₽
      const zБезналКоп = цел(1000000, 9000000);
      const возвратКоп = сл() < 0.12 ? цел(5000, 200000) : 0;

      // Кассир платил из ящика: строками «кому и за что»
      const список = [];
      let выплатыКоп = 0;
      const сколькоСтрок = сл() < 0.55 ? цел(1, 3) : 0;
      for (let i = 0; i < сколькоСтрок; i++) {
        const сумКоп = цел(50000, 2500000);
        выплатыКоп += сумКоп;
        список.push({ name: ПОСТАВЩИКИ[цел(0, ПОСТАВЩИКИ.length - 1)], sum: руб(сумКоп) });
      }
      // Иногда владелец довозит размен среди смены — из своего же сейфа
      const внесеноКоп = сл() < 0.08 ? цел(200000, 1000000) : 0;
      // Размен на следующую смену: обычно тот же, иногда меняется
      const оставилКоп = сл() < 0.15 ? цел(0, 1000000) : было;

      const должныКоп = было + zНалКоп - возвратКоп + внесеноКоп - выплатыКоп - оставилКоп;
      // Расхождение: чаще ноль, иногда мелочь, редко крупное
      let рКоп = 0;
      if (сл() < 0.22) рКоп = цел(-50000, 50000);
      if (сл() < 0.02) рКоп = цел(-800000, 800000);
      const полученоКоп = должныКоп + рКоп;

      rows.push({ id: id(), type: 'Смена', date: дт, till: касса, shift: смена,
        cashier: КАССИРЫ[цел(0, КАССИРЫ.length - 1)],
        openCash: руб(было), zCash: руб(zНалКоп), zCashless: руб(zБезналКоп),
        returnsCash: руб(возвратКоп), deposits: руб(внесеноКоп),
        payouts: руб(выплатыКоп), payoutList: список,
        kept: руб(оставилКоп), received: руб(полученоКоп),
        toAccount: 'сейф', cashlessAccount: 'банк' });

      // своя бухгалтерия
      разменКоп[касса] = оставилКоп;
      сейфКоп += полученоКоп - внесеноКоп;
      банкКоп += zБезналКоп;
      выручкаКоп += (zНалКоп - возвратКоп) + zБезналКоп;
      if (рКоп < 0) недостачиКоп += -рКоп; else излишкиКоп += рКоп;
    }
  }

  // Расход наличными из сейфа — раз в несколько дней
  if (сл() < 0.35) {
    const сумКоп = цел(100000, 4000000);
    rows.push({ id: id(), type: 'Расход', date: дт, category: СТАТЬИ[цел(0, СТАТЬИ.length - 1)],
      method: 'Наличные', account: 'сейф', amount: руб(сумКоп) });
    сейфКоп -= сумКоп;
  }
  // Расход со счёта
  if (сл() < 0.2) {
    const сумКоп = цел(300000, 8000000);
    rows.push({ id: id(), type: 'Расход', date: дт, category: СТАТЬИ[цел(0, СТАТЬИ.length - 1)],
      method: 'Перевод', account: 'банк', amount: руб(сумКоп) });
    банкКоп -= сумКоп;
  }
  // Владелец взял себе
  if (сл() < 0.08) {
    const сумКоп = цел(500000, 5000000);
    rows.push({ id: id(), type: 'Забор', date: дт, method: 'Наличные',
      account: 'сейф', amount: руб(сумКоп) });
    сейфКоп -= сумКоп;
    своиЗабралКоп += сумКоп;
  }
  // Владелец внёс свои
  if (сл() < 0.05) {
    const сумКоп = цел(1000000, 20000000);
    rows.push({ id: id(), type: 'Приход', date: дт, category: 'Внёс владелец',
      method: 'Наличные', account: 'сейф', amount: руб(сумКоп) });
    сейфКоп += сумКоп;
    своиВнёсКоп += сумКоп;
  }
  // Возврат от поставщика
  if (сл() < 0.04) {
    const сумКоп = цел(100000, 3000000);
    rows.push({ id: id(), type: 'Приход', date: дт, category: 'Возврат от поставщика',
      method: 'Наличные', account: 'сейф', amount: руб(сумКоп) });
    сейфКоп += сумКоп;
  }
  // Отвезли наличные в банк
  if (сл() < 0.06) {
    const сумКоп = цел(2000000, 30000000);
    rows.push({ id: id(), type: 'Перемещение', date: дт, category: 'Сдача в банк',
      account: 'сейф', toAccount: 'банк', amount: руб(сумКоп) });
    сейфКоп -= сумКоп; банкКоп += сумКоп;
  }
}

console.log('\nГод работы: ' + rows.length.toLocaleString('ru') + ' записей, ' +
  'выручка ' + руб(выручкаКоп).toLocaleString('ru') + ' ₽\n');

/* ========================================================================== */
console.log('— Деньги не взялись из воздуха и никуда не делись');
{
  const b = WM.accountBalances(rows, счета);
  const сейф = b.rows.find(function (a) { return a.id === 'сейф'; }).balance;
  const банк = b.rows.find(function (a) { return a.id === 'банк'; }).balance;

  check('СЕЙФ СОШЁЛСЯ С ТЕМ, ЧТО ТЕСТ СЧИТАЛ САМ',
    Math.abs(сейф - руб(сейфКоп)) < 0.005, сейф, руб(сейфКоп));
  check('СЧЁТ СОШЁЛСЯ С ТЕМ, ЧТО ТЕСТ СЧИТАЛ САМ',
    Math.abs(банк - руб(банкКоп)) < 0.005, банк, руб(банкКоп));
  check('ящиков в итогах нет вовсе', b.totals.till === 0, b.totals.till, 0);

  const j = WM.journal(rows, счета);
  check('ЖУРНАЛ ДВОЙНОЙ ЗАПИСИ СХОДИТСЯ В НОЛЬ ЗА ВЕСЬ ГОД', j.ok, j.total, 0);
}

console.log('\n— Выручка и расхождения');
{
  const t = WM.totals(rows, settings);
  check('ВЫРУЧКА ЗА ГОД СОШЛАСЬ ДО КОПЕЙКИ',
    Math.abs(t.revenue - руб(выручкаКоп)) < 0.005, t.revenue, руб(выручкаКоп));
  check('недостачи сошлись', Math.abs(t.short - руб(недостачиКоп)) < 0.005,
    t.short, руб(недостачиКоп));
  check('излишки сошлись', Math.abs(t.over - руб(излишкиКоп)) < 0.005,
    t.over, руб(излишкиКоп));
  check('смен посчитано столько, сколько записано',
    t.shifts === 365 * КАССЫ.length * СМЕНЫ.length, t.shifts, 365 * 4);
}

console.log('\n— Каждая смена по отдельности');
{
  const смены = rows.filter(function (r) { return r.type === 'Смена'; });
  let плохих = 0, несводимых = 0, первая = '';
  смены.forEach(function (r) {
    const c = WM.shiftCalc(r);
    // расхождение обязано быть ровно «получил − должны отдать»
    if (Math.abs(c.diff - WM.safeRound(c.received - c.handed)) > 0.005) {
      плохих++; if (!первая) первая = r.date + ' ' + r.till;
    }
    // и каждый совет обязан сводить кассу
    if (!c.ok) {
      const f = WM.shiftFix(c);
      f.list.forEach(function (x) {
        const s2 = Object.assign({}, r); s2[x.key] = x.need;
        if (!WM.shiftCalc(s2).ok) несводимых++;
      });
    }
  });
  check('РАСХОЖДЕНИЕ ВЕЗДЕ = ПОЛУЧИЛ − ДОЛЖНЫ ОТДАТЬ', плохих === 0,
    плохих ? плохих + ' смен, первая ' + первая : 'все ' + смены.length, 0);
  check('И КАЖДЫЙ СОВЕТ СВОДИТ КАССУ — НА ВСЕХ СМЕНАХ ГОДА', несводимых === 0,
    несводимых, 0);
}

console.log('\n— Кассовая книга за год');
{
  const b = WM.cashBook(rows, settings, null, null, счета);
  check('цепочка остатков не рвётся ни в одном дне',
    b.days.every(function (d, i) { return i === 0 || d.open === b.days[i - 1].close; }),
    b.days.length + ' дней', 'все дни');
  check('КНИГА СОШЛАСЬ С ОСТАТКОМ СЕЙФА',
    Math.abs(b.close - руб(сейфКоп)) < 0.005, b.close, руб(сейфКоп));
  check('и с формулой «было + пришло − ушло»',
    Math.abs(WM.safeRound(b.open + b.inSum - b.outSum) - b.close) < 0.005,
    WM.safeRound(b.open + b.inSum - b.outSum), b.close);
  check('книга не уходит в минус ни в одном дне',
    b.days.every(function (d) { return d.close >= -0.005; }),
    b.days.filter(function (d) { return d.close < 0; }).length + ' дней в минусе', 0);
}

console.log('\n— Свои деньги владельца');
{
  const own = WM.ownerFunds(rows);
  check('внесено сошлось', Math.abs(own.in - руб(своиВнёсКоп)) < 0.005, own.in, руб(своиВнёсКоп));
  check('забрано сошлось', Math.abs(own.out - руб(своиЗабралКоп)) < 0.005, own.out, руб(своиЗабралКоп));
  check('долг магазина = внёс − забрал',
    Math.abs(own.debt - руб(своиВнёсКоп - своиЗабралКоп)) < 0.005,
    own.debt, руб(своиВнёсКоп - своиЗабралКоп));

  const p = WM.pnl({ rows: rows });
  check('СВОИ ДЕНЬГИ НЕ ПОПАЛИ В ВЫРУЧКУ',
    Math.abs(p.revenue - руб(выручкаКоп)) < 0.005, p.revenue, руб(выручкаКоп));
  check('и забор владельца не съел прибыль',
    Math.abs(p.draw - руб(своиЗабралКоп)) < 0.005 && p.costTotal < p.revenue,
    p.draw, руб(своиЗабралКоп));
}

console.log('\n— Копейки за год не потерялись');
{
  /* Складываем все суммы года двумя способами: программой и целыми копейками.
     Если safeRound где-то теряет копейку, на 365 днях это вылезет. */
  let суммаКоп = 0, суммаПрог = 0;
  rows.forEach(function (r) {
    ['amount', 'zCash', 'zCashless', 'received', 'kept', 'payouts', 'deposits', 'returnsCash']
      .forEach(function (k) {
        if (r[k] == null || r[k] === '') return;
        суммаКоп += Math.round(r[k] * 100);
        суммаПрог = WM.safeRound(суммаПрог + r[k]);
      });
  });
  check('СУММА ВСЕХ ЧИСЕЛ ГОДА СОШЛАСЬ ДО КОПЕЙКИ',
    Math.abs(суммаПрог - руб(суммаКоп)) < 0.005, суммаПрог, руб(суммаКоп));
}

console.log('\n— Программа не задумывается на годовой базе');
{
  const t0 = Date.now();
  WM.accountBalances(rows, счета);
  WM.totals(rows, settings);
  WM.cashBook(rows, settings, null, null, счета);
  WM.journal(rows, счета);
  WM.pnl({ rows: rows });
  const мс = Date.now() - t0;
  check('весь пересчёт года укладывается в секунду', мс < 1000, мс + ' мс', 'меньше 1000 мс');
}

console.log('\nЗерно: ' + ЗЕРНО + ' (повторить: node tests/проверка-года.js ' + ЗЕРНО + ')');
console.log('Итог: ' + passed + ' проверок пройдено, ' + failed + ' провалено.');
process.exit(failed ? 1 : 0);
