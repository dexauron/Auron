/* ============================================================================
   Проверка на тысяче случайных магазинных дней.

   Обычные проверки берут примеры, которые придумал человек. Эта — наоборот:
   программа сама выдумывает магазин со случайными числами (сколько касс,
   сколько смен, сколько выручки, кто что вынул из ящика), а потом смотрит,
   не нарушилось ли ПРАВИЛО. Правила такие, что нарушиться они не могут
   ни при каких числах — если нарушились, значит в расчётах ошибка.

   Каждый магазин собирается по номеру («зерну»). Нашлась ошибка — в отчёте
   стоит номер, и тот же самый магазин собирается заново хоть через месяц:

       node tests/проверка-на-тысяче-дней.js          все 1000
       node tests/проверка-на-тысяче-дней.js 573      только магазин № 573
   ========================================================================== */
'use strict';
const path = require('path');
const E = require(path.join(__dirname, '..', 'js', 'engine.js'));

const РУБ = v => (Math.round(v * 100) / 100).toLocaleString('ru-RU');
const близко = (a, b, допуск) => Math.abs(a - b) <= (допуск === undefined ? 0.02 : допуск);

/* --- Случайные числа по номеру ---------------------------------------------
   Обычный Math.random() не годится: ошибка нашлась бы один раз и исчезла.
   Здесь каждый номер всегда даёт одну и ту же последовательность. */
function зерно(n) {
  let a = (n + 0x6d2b79f5) >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/* --- Выдумываем магазин ------------------------------------------------------ */
function магазин(номер) {
  const r = зерно(номер);
  const целое = (от, до) => от + Math.floor(r() * (до - от + 1));
  const деньги = (от, до) => Math.round((от + r() * (до - от)) * 100) / 100;
  const выбор = список => список[целое(0, список.length - 1)];

  const кассИтого = целое(1, 2);
  const счета = [];
  for (let i = 0; i < кассИтого; i++) {
    счета.push({ id: 'till' + i, name: 'Касса ' + (i + 1), kind: 'till',
      opening: 0, defaultCash: i === 0 });
  }
  счета.push({ id: 'safe', name: 'Сейф', kind: 'cash', opening: деньги(0, 50000) });
  счета.push({ id: 'bank', name: 'Расчётный счёт', kind: 'bank',
    opening: деньги(0, 100000), defaultCashless: true });

  const дней = целое(1, 28);
  const строки = [];
  // Размен, который лежит в каждой кассе на начало: он же opening счёта
  const размен = счета.filter(a => a.kind === 'till').map(a => {
    a.opening = деньги(0, 5000);
    return a.opening;
  });
  const вКассе = размен.slice();          // сколько лежит в каждом ящике сейчас
  const последнийФакт = размен.slice();   // чем закончилась последняя смена

  for (let д = 1; д <= дней; д++) {
    const дата = '2026-09-' + String(д).padStart(2, '0');

    for (let к = 0; к < кассИтого; к++) {
      const смен = целое(0, 2);
      for (let с = 0; с < смен; с++) {
        const zCash = деньги(0, 80000);
        const zCashless = r() < 0.15 ? 0 : деньги(0, 60000);
        // Вынуть больше, чем лежит в ящике, кассир не может
        const потолок = вКассе[к] + zCash;
        const payouts = потолок > 0 ? деньги(0, потолок) : 0;
        const расчёт = Math.round((вКассе[к] + zCash - payouts) * 100) / 100;
        // Иногда касса не сходится: недостача или излишек
        const расхождение = r() < 0.25 ? деньги(-800, 800) : 0;
        const factCash = Math.max(0, Math.round((расчёт + расхождение) * 100) / 100);

        строки.push({ type: E.T_SHIFT, date: дата, till: 'Касса ' + (к + 1),
          shift: выбор(['День', 'Ночь']), cashier: выбор(['Аня', 'Марат', 'Ольга']),
          openCash: вКассе[к], zCash, zCashless, payouts, factCash,
          account: 'till' + к, cashlessAccount: 'bank' });

        вКассе[к] = factCash;
        последнийФакт[к] = factCash;
      }
    }

    if (r() < 0.7) {
      строки.push({ type: E.T_DAY, date: дата,
        goodsCash: r() < 0.8 ? деньги(0, 30000) : 0,
        debtTaken: r() < 0.5 ? деньги(0, 40000) : 0,
        debtPaid: r() < 0.4 ? деньги(0, 20000) : 0 });
    }

    // Расходы магазина — с любого счёта
    for (let i = 0, n = целое(0, 3); i < n; i++) {
      строки.push({ type: E.T_OUT, date: дата,
        category: выбор(['Аренда', 'Коммунальные', 'ГСМ', 'Обед', 'Расходники', 'ЗП']),
        method: выбор(['Наличные', 'Карта']),
        account: выбор(счета).id, amount: деньги(1, 15000) });
    }
    // Переводы между счетами
    for (let i = 0, n = целое(0, 2); i < n; i++) {
      const откуда = выбор(счета), куда = выбор(счета);
      if (откуда.id === куда.id) continue;
      строки.push({ type: E.T_MOVE, date: дата, amount: деньги(1, 40000),
        account: откуда.id, toAccount: куда.id });
    }
    // Владелец взял себе
    if (r() < 0.15) {
      строки.push({ type: E.T_DRAW, date: дата, category: 'Забор владельца',
        method: 'Наличные', account: выбор(счета).id, amount: деньги(1, 50000) });
    }
    // Приход не от продаж
    if (r() < 0.1) {
      строки.push({ type: E.T_IN, date: дата, category: 'Прочий приход',
        method: 'Наличные', account: выбор(счета).id, amount: деньги(1, 20000) });
    }
  }

  return { счета, строки, последнийФакт, кассИтого, дней };
}

/* --- Правила, которые нарушиться не могут ----------------------------------- */
const ПРАВИЛА = [];
const правило = (имя, объяснение, проверка) =>
  ПРАВИЛА.push({ имя, объяснение, проверка });

правило('Остаток ящика — это факт последней смены',
  'Ящик пересчитывают руками при закрытии смены. Сколько кассир насчитал, ' +
  'столько там и есть — никакая другая запись остаток ящика не меняет.',
  м => {
    const b = E.accountBalances(м.строки, м.счета);
    for (let к = 0; к < м.кассИтого; к++) {
      const счёт = b.rows.find(a => a.id === 'till' + к);
      if (!близко(счёт.balance, м.последнийФакт[к])) {
        return 'в «' + счёт.name + '» программа насчитала ' + РУБ(счёт.balance) +
          ', а кассир в последнюю смену насчитал ' + РУБ(м.последнийФакт[к]);
      }
    }
    return '';
  });

правило('Перекладывание денег прибыль не меняет',
  'Увезли выручку в сейф или перекинули на счёт — деньги переложили, ' +
  'а не потратили. Прибыль от этого не может измениться ни на рубль.',
  м => {
    const было = E.pnl({ rows: м.строки }).net;
    const ещё = м.строки.concat([{ type: E.T_MOVE, date: '2026-09-15',
      amount: 33333.33, account: 'till0', toAccount: 'safe' }]);
    const стало = E.pnl({ rows: ещё }).net;
    return близко(было, стало) ? ''
      : 'прибыль была ' + РУБ(было) + ', после перевода стала ' + РУБ(стало);
  });

правило('Забор владельца прибыль не съедает',
  'Владелец берёт деньги уже из заработанного. Это не затрата магазина: ' +
  'в затраты забор не входит и прибыль не уменьшает.',
  м => {
    const было = E.pnl({ rows: м.строки });
    const ещё = м.строки.concat([{ type: E.T_DRAW, date: '2026-09-15',
      category: 'Забор владельца', method: 'Наличные',
      account: 'safe', amount: 12345.67 }]);
    const стало = E.pnl({ rows: ещё });
    if (!близко(было.net, стало.net)) {
      return 'прибыль была ' + РУБ(было.net) + ', после забора стала ' + РУБ(стало.net);
    }
    if (!близко(стало.draw - было.draw, 12345.67)) {
      return 'забор не встал отдельной строкой: было ' + РУБ(было.draw) +
        ', стало ' + РУБ(стало.draw);
    }
    return '';
  });

правило('Перевод денег не создаёт и не уничтожает',
  'Перевод с сейфа на счёт: на одном меньше, на другом ровно столько же больше. ' +
  'Перевод ИЗ ЯЩИКА — особый: из ящика деньги уже ушли через «выплаты» смены, ' +
  'поэтому ящик не уменьшается, а общая сумма растёт на эти деньги.',
  м => {
    const было = E.accountBalances(м.строки, м.счета).totals.total;

    const сСейфа = м.строки.concat([{ type: E.T_MOVE, date: '2026-09-15',
      amount: 7777.77, account: 'safe', toAccount: 'bank' }]);
    const после1 = E.accountBalances(сСейфа, м.счета).totals.total;
    if (!близко(после1, было)) {
      return 'перевод с сейфа на счёт изменил общую сумму: было ' + РУБ(было) +
        ', стало ' + РУБ(после1);
    }

    const изЯщика = м.строки.concat([{ type: E.T_MOVE, date: '2026-09-15',
      amount: 7777.77, account: 'till0', toAccount: 'safe' }]);
    const после2 = E.accountBalances(изЯщика, м.счета).totals.total;
    if (!близко(после2 - было, 7777.77)) {
      return 'инкассация из ящика посчиталась неверно: сумма выросла на ' +
        РУБ(после2 - было) + ' вместо ' + РУБ(7777.77);
    }
    const ящикБыл = E.accountBalances(м.строки, м.счета).rows.find(a => a.id === 'till0').balance;
    const ящикСтал = E.accountBalances(изЯщика, м.счета).rows.find(a => a.id === 'till0').balance;
    if (!близко(ящикБыл, ящикСтал)) {
      return 'ИНКАССАЦИЯ ВЫЧЛАСЬ ИЗ ЯЩИКА ВТОРОЙ РАЗ: было ' + РУБ(ящикБыл) +
        ', стало ' + РУБ(ящикСтал);
    }
    return '';
  });

правило('Расход из ящика ящик не уменьшает, но в затраты входит',
  'Аренда, оплаченная из кассы, уже сидит в «выплатах из ящика» той смены. ' +
  'Остаток ящика она второй раз не уменьшает — но затратой быть не перестаёт.',
  м => {
    const ящикБыл = E.accountBalances(м.строки, м.счета).rows.find(a => a.id === 'till0').balance;
    const затратыБыли = E.pnl({ rows: м.строки }).costTotal;
    const ещё = м.строки.concat([{ type: E.T_OUT, date: '2026-09-15',
      category: 'Аренда', method: 'Наличные', account: 'till0', amount: 9999.99 }]);
    const ящикСтал = E.accountBalances(ещё, м.счета).rows.find(a => a.id === 'till0').balance;
    const затратыСтали = E.pnl({ rows: ещё }).costTotal;
    if (!близко(ящикБыл, ящикСтал)) {
      return 'РАСХОД ВЫЧЕЛСЯ ИЗ ЯЩИКА ВТОРОЙ РАЗ: было ' + РУБ(ящикБыл) +
        ', стало ' + РУБ(ящикСтал);
    }
    if (!близко(затратыСтали - затратыБыли, 9999.99)) {
      return 'расход не попал в затраты: затраты выросли на ' +
        РУБ(затратыСтали - затратыБыли) + ' вместо ' + РУБ(9999.99);
    }
    return '';
  });

правило('Закуп товара расходом не считается',
  'Закуп уже вычтен из выручки, когда считали валовую прибыль. Если он ' +
  'записан ещё и расходом, тот же товар вычтется дважды и прибыль занизится.',
  м => {
    const было = E.pnl({ rows: м.строки }).costTotal;
    const ещё = м.строки.concat([{ type: E.T_OUT, date: '2026-09-15',
      category: 'Закуп товара', method: 'Наличные', account: 'safe', amount: 50000 }]);
    const стало = E.pnl({ rows: ещё }).costTotal;
    return близко(было, стало) ? ''
      : 'ЗАКУП ВОШЁЛ В ЗАТРАТЫ: было ' + РУБ(было) + ', стало ' + РУБ(стало);
  });

правило('От порядка записей ничего не зависит',
  'Владелец вносит записи как придётся: вечером за утро, задним числом. ' +
  'Прибыль и остатки по счетам обязаны получиться одни и те же.',
  м => {
    const r = зерно(м.строки.length + 7);
    const перемешано = м.строки.slice();
    for (let i = перемешано.length - 1; i > 0; i--) {
      const j = Math.floor(r() * (i + 1));
      const t = перемешано[i]; перемешано[i] = перемешано[j]; перемешано[j] = t;
    }
    const a = E.pnl({ rows: м.строки }), b = E.pnl({ rows: перемешано });
    if (!близко(a.net, b.net)) {
      return 'прибыль изменилась от перестановки записей: ' + РУБ(a.net) +
        ' против ' + РУБ(b.net);
    }
    const ба = E.accountBalances(м.строки, м.счета).totals;
    const бб = E.accountBalances(перемешано, м.счета).totals;
    return близко(ба.total, бб.total) ? ''
      : 'деньги изменились от перестановки записей: ' + РУБ(ба.total) +
        ' против ' + РУБ(бб.total);
  });

правило('Арифметика сходится до копейки',
  'Валовая = выручка − закуп. Чистая = валовая − затраты. Всего денег = ' +
  'наличные + безнал. Наличные = ящики + сейф. Округление это ломать не должно.',
  м => {
    const p = E.pnl({ rows: м.строки });
    if (!близко(p.gross, p.revenue - p.purchase)) {
      return 'валовая прибыль ' + РУБ(p.gross) + ' ≠ выручка ' + РУБ(p.revenue) +
        ' − закуп ' + РУБ(p.purchase);
    }
    if (!близко(p.net, p.gross - p.costTotal)) {
      return 'чистая прибыль ' + РУБ(p.net) + ' ≠ валовая ' + РУБ(p.gross) +
        ' − затраты ' + РУБ(p.costTotal);
    }
    const t = E.accountBalances(м.строки, м.счета).totals;
    if (!близко(t.total, t.cash + t.bank)) {
      return 'всего денег ' + РУБ(t.total) + ' ≠ наличные ' + РУБ(t.cash) +
        ' + безнал ' + РУБ(t.bank);
    }
    if (!близко(t.cash, t.till + t.safe)) {
      return 'наличные ' + РУБ(t.cash) + ' ≠ ящики ' + РУБ(t.till) +
        ' + сейф ' + РУБ(t.safe);
    }
    const сумма = E.accountBalances(м.строки, м.счета).rows
      .reduce((s, a) => s + a.balance, 0);
    return близко(сумма, t.total, 0.05) ? ''
      : 'сумма по счетам ' + РУБ(сумма) + ' ≠ итог ' + РУБ(t.total);
  });

правило('Выручка периода = выручка его частей',
  'Разрезали месяц пополам — сумма двух половин обязана дать тот же месяц. ' +
  'Иначе какой-то день считается дважды или теряется.',
  м => {
    const рубеж = '2026-09-15';
    const всё = E.totals(м.строки);
    const первая = E.totals(м.строки.filter(r => r.date <= рубеж));
    const вторая = E.totals(м.строки.filter(r => r.date > рубеж));
    if (!близко(всё.revenue, первая.revenue + вторая.revenue, 0.05)) {
      return 'месяц ' + РУБ(всё.revenue) + ', а половины дают ' +
        РУБ(первая.revenue + вторая.revenue);
    }
    return близко(всё.payouts, первая.payouts + вторая.payouts, 0.05) ? ''
      : 'выплаты из ящика: месяц ' + РУБ(всё.payouts) + ', половины ' +
        РУБ(первая.payouts + вторая.payouts);
  });

правило('Недостача и излишек — это одно и то же расхождение',
  'Расхождение либо минус (недостача), либо плюс (излишек), третьего нет. ' +
  'Сумма всех расхождений обязана равняться излишкам минус недостачи.',
  м => {
    const t = E.totals(м.строки);
    return близко(t.diff, t.over - t.short, 0.05) ? ''
      : 'расхождение ' + РУБ(t.diff) + ' ≠ излишки ' + РУБ(t.over) +
        ' − недостачи ' + РУБ(t.short);
  });

правило('Выплаты из ящика расписаны без перебора',
  'Программа складывает всё, на что ушли деньги из ящика, и сравнивает ' +
  'с выплатами по сменам. Расписать больше, чем вынули, нельзя.',
  м => {
    const c = E.tillPayoutCheck(м.строки, '2026-09', { accounts: м.счета });
    if (!c || !c.days) return '';
    for (const d of c.days) {
      const посчитано = Object.keys(d.parts || {})
        .reduce((s, k) => s + d.parts[k], 0);
      if (!близко(посчитано, d.explained, 0.05)) {
        return d.date + ': расшифровка по частям ' + РУБ(посчитано) +
          ' ≠ итог расшифровки ' + РУБ(d.explained);
      }
    }
    return '';
  });

/* --- Прогон ------------------------------------------------------------------ */
const один = process.argv[2] ? Number(process.argv[2]) : null;
const СКОЛЬКО = один !== null ? 1 : 1000;
const первый = один !== null ? один : 1;

let провалов = 0, магазинов = 0, дней = 0, записей = 0;
const сломанные = {};

console.log('— Тысяча случайных магазинов: правила, которые нарушиться не могут\n');

for (let н = первый; н < первый + СКОЛЬКО; н++) {
  const м = магазин(н);
  магазинов++; дней += м.дней; записей += м.строки.length;
  for (const п of ПРАВИЛА) {
    let беда;
    try { беда = п.проверка(м); }
    catch (e) { беда = 'расчёт упал с ошибкой: ' + e.message; }
    if (беда) {
      провалов++;
      if (!сломанные[п.имя]) {
        сломанные[п.имя] = true;
        console.log('  ❌ ' + п.имя);
        console.log('     ' + п.объяснение);
        console.log('     Магазин № ' + н + ': ' + беда);
        console.log('     Повторить: node tests/проверка-на-тысяче-дней.js ' + н);
        console.log('');
      }
    }
  }
}

if (!провалов) {
  for (const п of ПРАВИЛА) console.log('  ✅ ' + п.имя);
}

console.log('\nПроверено магазинов: ' + магазинов + ', дней: ' + дней +
  ', записей: ' + записей + '.');
console.log('Правил: ' + ПРАВИЛА.length + '. Нарушений: ' + провалов + '.');
process.exit(провалов ? 1 : 0);
