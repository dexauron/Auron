#!/usr/bin/env bash
# ============================================================================
#  Не сдавать сломанное.
#
#  Хук срабатывает, когда Claude собирается закончить работу. Если в папке
#  «Учёт-магазина» что-то поменялось, он гоняет проверки. Провалились —
#  Claude не отпускают: он получает отчёт и обязан доделать.
#
#  Проверки быстрые (расчёты и тысяча магазинов) идут всегда.
#  Браузерная — только если менялись экраны, стили или разметка: она
#  тяжёлая, и гонять её из-за правки в документе смысла нет.
#
#  Если хук мешает (например, проверки временно сломаны не по делу) —
#  уберите его из .claude/settings.json, раздел "hooks".
# ============================================================================
set -uo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
app="$root/Учёт-магазина"
cd "$root" || exit 0

# Ничего не трогали в программе — не мешаем
changed="$(git status --porcelain -- 'Учёт-магазина' 2>/dev/null)"
[ -n "$changed" ] || exit 0

command -v node >/dev/null 2>&1 || exit 0
[ -d "$app/tests" ] || exit 0

report=""
broken=0

run_suite() {
  local title="$1" file="$2" out=""
  [ -f "$app/$file" ] || return 0
  out="$(cd "$app" && node "$file" 2>&1)" && return 0
  broken=1
  report="$report

### $title — ПРОВАЛЕНО
$(printf '%s\n' "$out" | grep -E '❌|Итог|Ошибка|Error|error|Повторить' | head -25)"
}

run_suite "Расчёты" "tests/проверка-разбора.js"
run_suite "Тысяча случайных магазинов" "tests/проверка-на-тысяче-дней.js"

# Браузерную гоняем, только если менялся фронт
if printf '%s\n' "$changed" | grep -qE '\.(js|mjs|css|html)$'; then
  run_suite "Экраны в браузере" "tests/проверка-экранов.mjs"
fi

[ "$broken" -eq 0 ] && exit 0

python3 - "$report" <<'PY'
import json, sys
print(json.dumps({
  "decision": "block",
  "reason": "Проверки не прошли — работу сдавать нельзя. Разберись, из-за чего, "
            "и почини. Если правило изменилось намеренно и устарела сама "
            "проверка — поправь проверку и обязательно скажи об этом "
            "владельцу простыми словами." + sys.argv[1]
}, ensure_ascii=False))
PY
exit 0
