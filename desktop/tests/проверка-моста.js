/* ============================================================================
   Проверка моста Auron → полный учёт.  Запуск:  node tests/проверка-моста.js

   Мост переносит деньги из одной половины продукта в другую. Ошибка здесь
   не видна глазами: цифра на экране просто будет другой, и владелец узнает
   об этом, когда не сойдётся касса. Поэтому проверяем не «работает ли»,
   а ровно те вещи, на которых такой перенос обычно и ломается:

   1. Дата теряет тип и съезжает на день.
   2. Перевод между счетами переносится ДВУМЯ строками и превращается
      в расход, которого не было.
   3. Повторный запуск задваивает всё, что уже перенесено.
   4. Мост затирает записи, сделанные владельцем в самом полном учёте.
   5. Мост меняет цифры в закрытом месяце.
   6. Безнал попадает в остаток денежного ящика.
   ========================================================================== */
const path = require('path');
const КОРЕНЬ = path.join(__dirname, '..');
const МОСТ = require(path.join(КОРЕНЬ, 'js', 'auron-bridge.js'));

let passed = 0, failed = 0;
function check(name, ok, got, want) {
  if (ok) { passed++; console.log('  ✅ ' + name + (got !== undefined ? '  → ' + got : '')); }
  else { failed++; console.log('  ❌ ' + name + '  получено: ' + got + ', ожидалось: ' + want); }
}

/* --- Поддельная база Auron: ровно те листы, что читает мост --------------- */
