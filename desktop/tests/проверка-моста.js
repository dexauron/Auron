/* Хранилище, как в браузере: мост получает строку и разбирает сам.
   Даты помечаем так же, как это делает сборка Auron, — иначе проверка
   проверяла бы не то, что происходит на самом деле. */
function хранилище(db) {
  const raw = JSON.stringify(db, function (k, v) {
    return (this[k] instanceof Date) ? { __d: this[k].toISOString() } : v;
  });
  return { getItem: function (key) { return key === МОСТ.KEY ? raw : null; } };
}

/* Поддельный полный учёт: только то, чем пользуется мост */
function учёт(state) {
  const st = state || { accounts: [], dds: [], staff: [], settings: {} };
  return {
    state: st,
    settings: st.settings,
    closedTo: function () { return st.settings.closedTo || ''; },
    save: function () { st._saved = (st._saved || 0) + 1; }
  };
}

console.log('\n— Мост переносит деньги, а не их подобие');

const S1 = учёт();
const итог = МОСТ.sync(S1, хранилище(базаAuron()));

check('счета перенеслись', S1.state.accounts.length === 2, S1.state.accounts.length, 2);
check('карта распознана как безналичный счёт',
  S1.state.accounts.filter(function (a) { return a.kind === 'bank'; }).length === 1,
  S1.state.accounts.map(function (a) { return a.name + ':' + a.kind; }).join(', '), 'одна карта');

const ops = S1.state.dds;
const приходы = ops.filter(function (r) { return r.type === 'Приход'; });
const расходы = ops.filter(function (r) { return r.type === 'Расход'; });
const переводы = ops.filter(function (r) { return r.type === 'Перемещение'; });

check('приход вне смены на месте', приходы.length === 1, приходы.length, 1);
check('расход ровно один — аренда', расходы.length === 1 && расходы[0].category === 'Аренда',
  расходы.map(function (r) { return r.category; }).join(','), 'Аренда');
check('ПЕРЕВОД НЕ СТАЛ РАСХОДОМ', переводы.length === 1, переводы.length, 1);
check('у перевода есть откуда и куда',
  переводы[0] && переводы[0].account === 'Наличные' && переводы[0].toAccount === 'Карта Сбербанк',
  переводы[0] && (переводы[0].account + ' → ' + переводы[0].toAccount), 'Наличные → Карта');
check('ПОЛОВИНА ПЕРЕВОДА БЕЗ ПАРЫ НЕ ПЕРЕНЕСЕНА',
  !ops.some(function (r) { return r.note === 'потерялась'; }), 'нет', 'нет');

check('ДАТА НЕ СЪЕХАЛА', приходы[0].date === '2026-09-16', приходы[0].date, '2026-09-16');
check('БЕЗНАЛ НЕ ПОПАЛ В ЯЩИК', приходы[0].method === 'Безнал', приходы[0].method, 'Безнал');
check('наличный расход помечен наличными', расходы[0].method === 'Наличные',
  расходы[0].method, 'Наличные');

check('сотрудник перенесён один раз, а не по строке табеля',
  S1.state.staff.length === 1, S1.state.staff.length, 1);
check('ставка сотрудника перенеслась', S1.state.staff[0].rate === 2500, S1.state.staff[0].rate, 2500);
check('мост отчитался числами', итог && итог.operations === ops.length, JSON.stringify(итог), 'совпало');

console.log('\n— Смена приезжает сменой, а не россыпью строк');

const смены = S1.state.dds.filter(function (r) { return r.type === 'Смена'; });
check('смена перенеслась', смены.length === 1, смены.length, 1);
check('Z-наличные на месте', смены[0] && смены[0].zCash === 90000, смены[0] && смены[0].zCash, 90000);
check('безнал отдельно от наличных', смены[0] && смены[0].zCashless === 30000,
  смены[0] && смены[0].zCashless, 30000);
check('ВЫПЛАТЫ ИЗ ЯЩИКА УЧТЕНЫ ВСЕ: и поставщикам, и прочие',
  смены[0] && смены[0].payouts === 17000, смены[0] && смены[0].payouts, 17000);
check('и видно, за что платили', смены[0] && смены[0].payoutList.length === 2,
  смены[0] && смены[0].payoutList.map(function (x) { return x.name; }).join(', '), '2 строки');
check('оставил в ящике', смены[0] && смены[0].kept === 5000, смены[0] && смены[0].kept, 5000);
check('забрал', смены[0] && смены[0].received === 68000, смены[0] && смены[0].received, 68000);
check('кассир не потерялся', смены[0] && смены[0].cashier === 'Марина', смены[0] && смены[0].cashier, 'Марина');

/* Главное: строки, которыми Auron разложил смену по «БАЗЕ», не должны
   приехать ещё и отдельными приходами — иначе выручка удвоится. */
const выручкаСмены = S1.state.dds.filter(function (r) {
  return r.type === 'Приход' && r.date === '2026-09-15' && r.amount === 120000;
});
check('ВЫРУЧКА СМЕНЫ НЕ ЗАДВОИЛАСЬ', выручкаСмены.length === 0, выручкаСмены.length, 0);
check('а не относящийся к смене расход остался',
  S1.state.dds.some(function (r) { return r.category === 'Аренда'; }), 'остался', 'остался');

console.log('\n— Повторный запуск ничего не задваивает');

const былоОпераций = S1.state.dds.length;
МОСТ.sync(S1, хранилище(базаAuron()));
check('ПОСЛЕ ВТОРОГО ЗАПУСКА СТОЛЬКО ЖЕ', S1.state.dds.length === былоОпераций,
  S1.state.dds.length, былоОпераций);
МОСТ.sync(S1, хранилище(базаAuron()));
check('и после третьего тоже', S1.state.dds.length === былоОпераций,
  S1.state.dds.length, былоОпераций);

console.log('\n— Чужие руки: записи владельца неприкосновенны');

const S2 = учёт();
S2.state.dds.push({ id: 'моя-1', type: 'Расход', date: '2026-09-15', category: 'Обед',
  amount: 300, note: 'записал сам' });
S2.state.accounts.push({ id: 'мой-счёт', name: 'Наличные', kind: 'cash', opening: 1 });
МОСТ.sync(S2, хранилище(базаAuron()));

check('СВОЯ ЗАПИСЬ НА МЕСТЕ',
  S2.state.dds.some(function (r) { return r.id === 'моя-1' && r.note === 'записал сам'; }),
  'на месте', 'на месте');
check('свой счёт не задвоился одноимённым из Auron',
  S2.state.accounts.filter(function (a) { return a.name === 'Наличные'; }).length === 1,
  S2.state.accounts.map(function (a) { return a.name; }).join(','), 'одни Наличные');

console.log('\n— Закрытый месяц не меняется сам собой');

const S3 = учёт();
МОСТ.sync(S3, хранилище(базаAuron()));
const зеркалоДо = S3.state.dds.filter(function (r) { return r.date === '2026-09-15'; }).length;
S3.state.settings.closedTo = '2026-09-30';     // владелец запер сентябрь

const изменённая = базаAuron();
изменённая['БАЗА'][2][5] = 999999;             // «аренда» задним числом стала другой
МОСТ.sync(S3, хранилище(изменённая));

const аренда = S3.state.dds.filter(function (r) { return r.category === 'Аренда'; })[0];
check('ЦИФРА В ЗАКРЫТОМ МЕСЯЦЕ НЕ ПОДМЕНИЛАСЬ', аренда && аренда.amount === 40000,
  аренда && аренда.amount, 40000);
check('и записи из закрытого месяца не пропали',
  S3.state.dds.filter(function (r) { return r.date === '2026-09-15'; }).length === зеркалоДо,
  S3.state.dds.filter(function (r) { return r.date === '2026-09-15'; }).length, зеркалоДо);

console.log('\n— Когда Auron рядом нет');

const S4 = учёт();
const пусто = МОСТ.sync(S4, { getItem: function () { return null; } });
check('мост молча ничего не делает', пусто === null, String(пусто), 'null');
check('и программа остаётся с пустой базой, а не с мусором',
  S4.state.dds.length === 0, S4.state.dds.length, 0);

const битое = МОСТ.sync(учёт(), { getItem: function () { return '{это не json'; } });
check('битая база Auron не роняет запуск', битое === null, String(битое), 'null');

console.log('\nИтог: ' + passed + ' проверок пройдено, ' + failed + ' провалено.');
process.exit(failed ? 1 : 0);
