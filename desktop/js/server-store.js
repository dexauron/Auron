/* ============================================================================
   Хранение базы в таблице владельца — когда полный учёт открыт как
   Auron Finance на сервере (Apps Script).

   ЗАЧЕМ. Сама программа считает и хранит всё в браузере. Для папки на
   флешке это правильно: ничего никуда не уходит. Но внутри Auron Finance
   страница живёт на временном адресе Google, память браузера там может
   обнулиться между обновлениями, и записи пропали бы молча — без ошибки,
   просто в один день пустой «Пульт».

   ПОЭТОМУ здесь база берётся из таблицы владельца при открытии и
   возвращается в неё при каждом изменении. Таблица — то же место, где
   лежат его смены и операции; она переезжает с ним на любое устройство.

   ПОРЯДОК ВАЖЕН. Этот файл подключается ДО `store.js`: тот читает базу
   сразу при загрузке, и подложить её нужно раньше, иначе программа
   откроется пустой, а через секунду перерисуется — владелец успеет
   увидеть нули и решить, что данные пропали.
   ========================================================================== */
(function () {
  'use strict';

  if (!window.AURON_SERVER) return;          // обычная папка — ничего не меняем

  var KEY = 'store_erp_v1';                  // тот же ключ, что у store.js
  var BOOT = window.AURON_BOOT || {};
  var ssId = BOOT.ssId || '';

  /* 1. База владельца — в память браузера, до того как её прочитает store.js.
        Пустую не подкладываем: на первом запуске в браузере может уже лежать
        что-то набранное, и затирать это нечем. */
  try {
    if (BOOT.uchet) localStorage.setItem(KEY, BOOT.uchet);
  } catch (e) { /* приватное окно — работаем как есть */ }

  /* 2. Сохранение обратно в таблицу.
        Пишем не на каждое нажатие: каждая запись в таблицу — обращение к
        серверу, а владелец правит форму по букве. Ждём паузу, а при уходе
        со страницы сохраняем немедленно. */
  var таймер = null, идёт = false, ждёт = false, ПАУЗА = 1500;

  function показать(текст, плохо) {
    var el = document.getElementById('saveState');
    if (!el) return;
    el.innerHTML = '<span class="saved-dot' + (плохо ? ' off' : '') + '"></span><span>' + текст + '</span>';
  }

  function отправить() {
    if (идёт) { ждёт = true; return; }       // предыдущая ещё летит
    var json = '';
    try { json = localStorage.getItem(KEY) || ''; } catch (e) { return; }
    if (!json) return;
    идёт = true;
    показать('Сохраняю в вашу таблицу…');
    try {
      window.google.script.run
        .withSuccessHandler(function (r) {
          идёт = false;
          if (r && r.__error) { показать('Не сохранилось: ' + r.__error, true); return; }
          показать('Сохранено в вашей таблице');
          if (ждёт) { ждёт = false; отправить(); }
        })
        .withFailureHandler(function (e) {
          идёт = false;
          /* Молчать нельзя: владелец продолжит записывать, считая, что всё
             легло в таблицу. Данные при этом остаются в браузере — то есть
             не потеряны, но и не переехали. */
          показать('Не сохранилось — проверьте связь', true);
          if (window.console) console.warn('полный учёт: сохранение', e && e.message);
        })
        .uchetSave({ ssId: ssId, json: json });
    } catch (e) { идёт = false; показать('Не сохранилось — нет связи', true); }
  }

  function отложить() {
    clearTimeout(таймер);
    таймер = setTimeout(отправить, ПАУЗА);
  }

  /* 3. Ловим сохранение программы. store.js к этому моменту ещё не загружен,
        поэтому оборачиваем его позже — когда он появится. */
  function обернуть() {
    var S = window.WMStore;
    if (!S || !S.save || S.__auronWrapped) return !!(S && S.__auronWrapped);
    var было = S.save;
    S.save = function () {
      var r = было.apply(this, arguments);
      отложить();
      return r;
    };
    S.__auronWrapped = true;
    показать('Записи хранятся в вашей таблице');
    return true;
  }

  if (!обернуть()) {
    var попытки = 0;
    var ждём = setInterval(function () {
      if (обернуть() || ++попытки > 100) clearInterval(ждём);
    }, 50);
  }

  /* Уходит со страницы — сохраняем сейчас, а не через полторы секунды.
     На телефоне вкладку закрывают сразу после записи, и отложенное
     сохранение просто не успевало бы уйти. */
  document.addEventListener('visibilitychange', function () {
    if (document.visibilityState === 'hidden') { clearTimeout(таймер); отправить(); }
  });
  window.addEventListener('pagehide', function () { clearTimeout(таймер); отправить(); });

  window.AuronServer = { save: отправить, ssId: ssId, boot: BOOT };
})();
